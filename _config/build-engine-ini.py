#!/usr/bin/env python3
"""Собирает Engine.ini сборки: ванильный блок [Core.System] дословно + наш
[SystemSettings]. Блок Paths переписывать руками нельзя - это 84 строки путей к
контенту плагинов, и одна потерянная строка стоит незагруженного контента.

⚠️ ОТСТАЛ ОТ _config/Engine.ini - НЕ ЗАПУСКАТЬ ВСЛЕПУЮ (2026-10-25, переезд на 3.0.1).
Engine.ini пака с тех пор правили руками поверх этого сборщика: прогон 25.10 выдал файл
на 208 строк короче живого, наша настройка потерялась бы. Сменить ванильный блок Paths
под новую версию игры - _config/swap-core-paths.py <Engine.ini> <vanilla/Engine.ini>: он
меняет ТОЛЬКО строки Paths=, остальное оставляет байт в байт. Сюда вернуться, только
когда TUNING снова совпадёт с живым файлом (diff пуст)."""
from pathlib import Path

PACK = Path(r"D:\work\ai_sandbox\ConanExiles")
VANILLA = PACK / "_config" / "vanilla" / "Engine.ini"
OUT = PACK / "_unpacked" / "KrinikConanGraphics" / "Engine.ini"  # мод графики, с 2026-10-30

TUNING = """
; ---------------------------------------------------------------------------
; Блок сборки Krinik. Всё, что ниже, дописано поверх ванильного [Core.System].
;
; ПОЧЕМУ ЗДЕСЬ ТАК МАЛО. Правка ini НЕ является проверкой: в Palworld четырнадцать
; заходов "по одному cvar-у через ini" дали четырнадцать ложных оправданий подряд,
; потому что игра затирала строки при входе в мир (EXP-0009). У Конана та же
; болезнь наблюдается прямо: все пять конфигов переписаны игрой при выходе из
; сессии 08.09.2026 0:01:58. Поэтому сюда едет только то, что уже проверено
; наблюдением ЛИБО читается на старте движка и иначе не проверяется вовсе.
; Кандидаты, ждущие живой проверки консолью, лежат в Engine.ini.candidates.ini
; и НЕ раскатываются.
; ---------------------------------------------------------------------------
[SystemSettings]

; --- DLSS -------------------------------------------------------------------
; ГЛАВНАЯ СТРОКА ФАЙЛА. Владелец просил "DLSS 4.5". Выяснилось, что DLSS 4.5 -
; это официальное имя NVIDIA (SDK 310.5.0, январь 2026, добавил пресеты L и M),
; и в игре УЖЕ лежит nvngx_dlss.dll ровно версии 310.5.0. То есть 4.5 был на
; месте с самого начала - не выбран был только пресет.
;
; Шкала снята из строк самого билда (help-текст cvar-а):
;   0 = пресет по умолчанию   1..7 = A..G   10 = J   11 = K   12 = L   13 = M
; Берём M. Основание - DLSS Programming Guide рев. 310.6.0, раздел 3.12:
; "Preset M: даёт улучшения качества, сравнимые с Preset L, но по скорости
; ближе к пресетам J и K". L резче, но дороже (+150 МБ VRAM в 4K) и ПРИНУДИТЕЛЬНО
; переходит на автоэкспозицию, что меняет вид картинки в игре со своей экспозицией.
; Откат: 11 = K, штатное поведение NVIDIA App для режимов Качество/Баланс/DLAA.
; [NOT-TESTED] на глаз владельцем - это класс "на вкус", и судить картинку ему.
r.NGX.DLSS.Preset=13

; --- Дальность --------------------------------------------------------------
; ⚠ ЧЕСТНОЕ ПРЕДУПРЕЖДЕНИЕ ПО СЛЕДУЮЩИМ ЧЕТЫРЁМ СТРОКАМ.
; В бинарнике игры найдены СТРОКИ ФОРМАТА консольных команд, которые игра
; выполняет сама: "sg.ViewDistanceQuality={0}", "r.ViewDistanceScale=%d",
; "r.Shadow.DistanceScale=%d", "r.SkeletalMeshLODBias=-10". Команда из консоли
; имеет приоритет SetByConsole (0x0E), а [SystemSettings] - всего 0x04. Значит
; игра, применяя свои настройки графики, ПЕРЕБИВАЕТ эти строки, и надёжный рычаг
; дальности здесь - не ini, а группа sg.ViewDistanceQuality в GameUserSettings.ini
; (в этом билде она принимает 4 = Cinematic, не только 3).
; Строки оставлены как нижняя граница на случай, если игра применит их не всегда,
; и как явная запись гипотезы. Проверяется одним заходом: открыть консоль в мире
; и ввести имя cvar-а без значения - оно напечатает ДЕЙСТВУЮЩЕЕ значение.
; [NOT-TESTED]
r.ViewDistanceScale=2.0

; Листва и трава: без них ViewDistanceScale поднимает только дальний рельеф,
; а кусты по-прежнему обрываются кругом вокруг игрока.
; [NOT-TESTED]
foliage.LODDistanceScale=2.0
grass.CullDistanceScale=2.0

; Меши дальних объектов переключаются на грубый LOD позже.
; ВНИМАНИЕ, НАПРАВЛЕНИЕ ОБРАТНОЕ: help-текст говорит "большие значения переводят
; LOD раньше, 2 = вдвое ближе". Значит для БОЛЬШЕЙ дальности нужно МЕНЬШЕ 1.
; [NOT-TESTED]
r.StaticMeshLODDistanceScale=0.75
"""

CANDIDATES = """; Кандидаты для ЖИВОЙ проверки консолью. Этот файл НЕ раскатывается в игру.
;
; Порядок работы (правило 2 конспекта researches/ue5-cvars/README.md в KUMM):
; сначала консоль в живой сцене, по ОДНОМУ cvar-у за заход, значение сверять
; ДО и ПОСЛЕ; в Engine.ini едет уже победитель. Консоль в Enhanced по умолчанию
; не открывается - её включает [/script/engine.inputsettings] в Input.ini.
;
; --- ДЫМКА НА ДАЛЬНИХ ПЛАНАХ ---------------------------------------------
; Штатный выключатель игры уже применён: Game.ini -> [Settings.Video] VolumetricFog=0.
; Если дымка осталась - она идёт от атмосферы, а не от объёмного тумана.
; Проверять строго по одному; r.Fog=0 стоит ПОСЛЕДНИМ: он убирает и глубину
; сцены, картинка становится плоской (предупреждение из разведки и из ветки
; Funcom "Hazy shade of Conan").
r.VolumetricFog=0
r.SkyAtmosphere.AerialPerspectiveLUT.FastApplyOnOpaque=0
r.SupportSkyAtmosphereAffectsHeightFog=0
r.VolumetricCloud=0
r.FogDensity=0.03
r.FogStartDistance=6
r.Fog=0

; --- СОБСТВЕННЫЕ РЫЧАГИ КОНАНА (dw.*) ------------------------------------
; ⚠ ОНИ ЖИВУТ В ДРУГОЙ СЕКЦИИ. Найдено 08.09.2026: три независимых источника -
; рецепт настройки Totchinuko, исходники менеджера серверов Trebuchet и
; docker-конфиг acelan - кладут имена dw.* в отдельную секцию
; [/Script/ConanSandbox.SystemSettings], а НЕ в [SystemSettings]. В ванильном
; Engine.ini такой секции нет вовсе, и её отсутствие объясняет "правка не
; сработала" раньше любых гипотез о значениях: проверять надо не значение, а адрес.
;
; Имя есть в бинарнике - это НЕ доказательство, что cvar зарегистрирован в
; консоли. Проверять чтением значения через консоль.
;
; Единственное известное значение во всей семье, и то из чужого кода: Trebuchet
; пишет dw.EnableAISpawning как "0" при выключенном спавне, то есть 1 = включён.
[/Script/ConanSandbox.SystemSettings]
dw.LowPerformanceFog=0
dw.LowPerformanceMaterials=0
"""


def main():
    head = VANILLA.read_text(encoding="utf-8-sig").rstrip("\n")
    OUT.write_text(head + "\n" + TUNING, encoding="utf-8")
    (PACK / "_config" / "Engine.ini.candidates.ini").write_text(CANDIDATES, encoding="utf-8")
    print(f"записано: {OUT} ({OUT.stat().st_size} байт)")
    print(f"записано: Engine.ini.candidates.ini")
    # Контроль: блок Paths обязан доехать целиком.
    src_paths = sum(1 for l in VANILLA.read_text(encoding="utf-8-sig").splitlines()
                    if l.startswith("Paths="))
    dst_paths = sum(1 for l in OUT.read_text(encoding="utf-8").splitlines()
                    if l.startswith("Paths="))
    print(f"контроль Paths=: ванильных {src_paths}, в результате {dst_paths} -> "
          + ("СОШЛОСЬ" if src_paths == dst_paths and src_paths > 0 else "РАСХОЖДЕНИЕ"))


if __name__ == "__main__":
    main()
