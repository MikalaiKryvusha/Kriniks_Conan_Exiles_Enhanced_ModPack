"""
Проверка текста руководства пользователя на классы фраз, которые владелец запретил 2026-10-31 (KUMM plans/35, Г11 п. 8):
оправдания и «чего нет», внутренняя механика, «само делается», починки наших багов, «читаемость» не к тексту.
«Игроку ПОЕБАТЬ!!! что там нахуй идет и как» · «ТУпых оптавданий Клода ДОХУЯ» · «это класс ошибки» (владелец, 17:25–17:47).
Запуск: python -I guide_lint.py <guide.html> — код 0 чисто, 1 найдены фразы (каждая с номером строки и правилом).
build-docs.py зовёт её перед печатью PDF.
[NOT-TESTED]
"""
import html
import re
import sys
from pathlib import Path

RULES = [
    (r"\bнет\b[^.<]{0,40}\b(в архиве|в сборке)|в (архиве|сборке)[^.<]{0,20}\bнет\b", "строка о том, чего НЕТ"),
    (r"не перезаписыва", "оправдание «не перезаписывает»"),
    (r"при этом [^.<]{0,40}(обычн|как раньше|сохраня|продолжа)", "«при этом работает как обычно» — оправдание"),
    (r"так устроен", "оправдание «так устроен»"),
    (r"починил|пофиксил|исправлен баг|исправлена ошибка нашего", "починка нашего бага"),
    (r"читаемост[а-я]* (выстрел|стрел|полёт|звук|прицел)", "«читаемость» не к тексту"),
    (r"порядок загрузки|загрузчик UE4SS|сверяются со списком|записывается в журнал", "внутренняя механика"),
    (r"(возвращается|сохраняется|настраивается|включается) одной клавишей", "класс «само делается»"),
    (r"как в старых «Свитках»|олдскул", "жаргон"),
]


def text_lines(path):
    raw = Path(path).read_text(encoding="utf-8")
    raw = re.sub(r"<style.*?</style>", "", raw, flags=re.S)
    raw = re.sub(r"<!--.*?-->", "", raw, flags=re.S)
    for n, line in enumerate(raw.splitlines(), 1):
        t = html.unescape(re.sub(r"<[^>]+>", "", line)).strip()
        if t:
            yield n, t


def main(path):
    hits = 0
    for n, t in text_lines(path):
        for pat, why in RULES:
            if re.search(pat, t, flags=re.I):
                print(f"{path}:{n}: {why}: {t[:140]}")
                hits += 1
    print(f"guide-lint: {hits} фраз(ы) запрещённых классов" if hits else "guide-lint: чисто")
    return 1 if hits else 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    sys.exit(main(sys.argv[1]))
