-- Вызов только руками, чтобы не сработало само посреди игры.
-- КЛАССЫ ДОБЫТЫ ОФЛАЙН, А НЕ УГАДАНЫ. 09.09.2026 индекс IoStore (138 424 пути,
-- researches/ue5-iostore-index) показал устройство погоды Конана:
