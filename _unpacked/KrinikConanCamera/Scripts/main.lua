-- ======================= УДЕРЖАНИЕ КАМЕРЫ =======================
--
-- ЗАЧЕМ. Наблюдение владельца: «Игра смещает в момент нажатия, но моментально
-- скидывает смещение как в стоке». То есть наша запись ДОХОДИТ (камера дёргается
-- на нажатии), а игра возвращает своё следующим же кадром. Значит SocketOffset —
-- правильное место, и вопрос только в том, кто пишет последним.
--
-- ⚠️ ЭТОТ БЛОК УЖЕ ОДИН РАЗ ИСЧЕЗ. Правка раскладки нумпада обрезала файл по
-- строке «загружен…», а удержание стояло ниже неё — и владелец запускал версию
-- БЕЗ УДЕРЖАНИЯ ВООБЩЕ. Внешне это выглядело правдоподобно («дёрганье ушло»),
-- и повело разбор по ложному следу. Держать блок ВЫШЕ финальной строки журнала.

hold_calls = 0        -- глобальная намеренно: её читает самопроверка ниже

-- Ограничитель нужен ТОЛЬКО хуку тика: он срабатывает для КАЖДОГО актора, а не
-- только для персонажа. Покадровому циклу он вреден - он и есть та самая пила,
-- ради которой всё затевалось, - поэтому цикл его снимает.
local HOLD_MIN_INTERVAL = 0.01
local rate_limit = true
local last_hold = 0
local last_report = 0

-- ⚠️ ДРЕЙФ. Прибор 08.09.2026 читал смещение ПОСЛЕ своей же записи и печатал
-- "в компоненте = хотим" - то есть доказывал сам себя, а не отсутствие чужой
-- правки. Полтора часа разбора ушло на гипотезы, которые это чтение не могло
-- ни подтвердить, ни опровергнуть. Теперь читаем ДО записи и копим максимум за
-- секунду: ноль = между нашими записями смещение никто не трогает (значит и
-- пилы по нему нет), заметная величина = игра тянет его обратно, и тогда
-- частота записи решает всё.
local drift = { x = 0, y = 0, z = 0, len = 0 }
local drift_ready = false
local calls_since_report = 0

local function hold_camera()
    hold_calls = hold_calls + 1

    -- Цель наша - драться не с чем. Это и есть разница между лечением причины
    -- и подпоркой: тут удержание просто перестаёт быть нужным.
    if target_owned then return end
    if not (arm and arm:IsValid()) then return end
    local now = os.clock()
    if rate_limit and now - last_hold < HOLD_MIN_INTERVAL then return end
    last_hold = now
    calls_since_report = calls_since_report + 1

    -- ЧТЕНИЕ ДО ЗАПИСИ - это и есть измерение.
    if drift_ready then
        local b = arm.SocketOffset
        local dx, dy, dz = math.abs(b.X - cfg.offset_x), math.abs(b.Y - cfg.offset_y),
                           math.abs(b.Z - cfg.offset_z)
        if dx > drift.x then drift.x = dx end
        if dy > drift.y then drift.y = dy end
        if dz > drift.z then drift.z = dz end
        if cfg.arm_length >= 0 then
            local dl = math.abs(arm.TargetArmLength - cfg.arm_length)
            if dl > drift.len then drift.len = dl end
        end
    end
    drift_ready = true

    -- Структуру ЦЕЛИКОМ: UE4SS отдаёт структурное свойство копией, и правка
    -- полей копии в объект не попадает.
    arm.SocketOffset = { X = cfg.offset_x, Y = cfg.offset_y, Z = cfg.offset_z }
    if cfg.arm_length >= 0 then
        arm.TargetArmLength = cfg.arm_length
    end

    -- ОБРАТНОЕ ЧТЕНИЕ раз в секунду. Без него «работает или нет» — вопрос веры,
    -- а три разных отказа (запись не прошла · игра перебила · удержание вообще
    -- не запускалось) выглядят одинаково и лечатся по-разному. Все три уже
    -- случились в этой сессии.
    if cfg.logging_enabled and now - last_report >= 1.0 then
        last_report = now
        log("ДРЕЙФ до записи за секунду (макс): ΔX=%.4f ΔY=%.4f ΔZ=%.4f Δдлина=%.4f | "
            .. "записей за секунду=%d | всего вызовов=%d",
            drift.x, drift.y, drift.z, drift.len, calls_since_report, hold_calls)
        drift.x, drift.y, drift.z, drift.len = 0, 0, 0, 0
        calls_since_report = 0
    end
end

-- ⚠️ ТАЙМЕР ОБЯЗАН ОСТАНАВЛИВАТЬСЯ, А НЕ КРУТИТЬСЯ ВХОЛОСТУЮ.
-- 08.09.2026 он продолжал работать 60 раз в секунду уже после того, как драка
-- стала не нужна (hold_camera просто выходил первой строкой), а сверху добавился
-- сторож цели на 20 вызовов в секунду. Два потока заданий в одну очередь UE4SS -
-- это ровно условия открытого бага #1180 (падение в process_simple_actions при
-- накладывающихся ExecuteInGameThread). Игра упала у владельца после нескольких
-- минут нормальной работы: EXCEPTION_ACCESS_VIOLATION 0x0c, стек из одних кадров
-- UE4SS. Цена холостого таймера - крэш, поэтому он теперь сам себя гасит.
local function start_timer(why)
    log("удержание таймером %d мс (%s)", cfg.reapply_interval_ms, why)
    local function timer()
        if target_owned then
            log("удержание остановлено: цель наша, драка не нужна")
            return
        end
        ExecuteInGameThreadWithDelay(cfg.reapply_interval_ms, function()
            ExecuteInGameThread(function() pcall(hold_camera) end)
            timer()
        end)
    end
    timer()
end

