local hub_seen_version = nil
local function hub_take_set()
    local okv, ver = pcall(function() return ModRef:GetSharedVariable("KrinikSettingsVersion") end)
    if not okv or ver == nil or ver == hub_seen_version then return end
    hub_seen_version = ver
    local oks, set = pcall(function() return ModRef:GetSharedVariable("KrinikCameraSet") end)
    if not oks or type(set) ~= "string" or set == "" then return end
    local by_id = {}
    for id, v in set:gmatch("([%w_]+)=([^;]+)") do by_id[id] = v end
    local n, old_length = 0, cfg.arm_length
    for k, id in pairs(HUB_KEYS) do
        local v = by_id[id]
        if v ~= nil then
            if type(cfg[k]) == "boolean" then cfg[k] = (v == "true") else cfg[k] = tonumber(v) or cfg[k] end
            n = n + 1
        end
    end
    -- дистанцию переставляем, только если её и меняли в окне: иначе «Сохранить» сбросило бы то, что игрок накрутил колесом
    local moved = cfg.arm_length ~= old_length
    apply(moved)
    if moved then desired_zoom = cfg.arm_length end
    pcall(write_config)
    log("ОКНО «Моды Krinik'а»: принято %d настроек (номер %s): высота %.1f · вбок %.1f · дистанция %.1f · наклон %.1f° · колесо %.0f–%.0f · резкий %s · плавность %.1f",
        n, tostring(ver), cfg.offset_z, cfg.offset_y, cfg.arm_length, cfg.camera_pitch, cfg.zoom_min, cfg.zoom_max, tostring(cfg.own_arm_length),
        cfg.zoom_interp_speed)
end
