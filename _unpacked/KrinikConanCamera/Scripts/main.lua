            log("      RelativeLocation X=%.1f Y=%.1f Z=%.1f", rl.X, rl.Y, rl.Z)
        end)
    end

    -- 3. Менеджер камеры: он и есть последняя инстанция, если вид считает он
    pcall(function()
        local pc = FindFirstOf("PlayerController")
        if pc and pc:IsValid() then
