-- ================ РАЗВЕДКА НАКЛОНА ВЗГЛЯДА ================
--
-- ЗАЧЕМ. Наклон («смотреть на героя сверху вниз, как в Обливионе») - это
-- ПОВОРОТ камеры, а не сдвиг штанги; сдвигом его пытались добыть весь день
-- 10.09.2026 и не добыли (разбор - у target_offset_z выше). Прежде чем
-- заводить настройку наклона, надо узнать ТРИ факта, и все три - у игры, а не
-- у меня в голове:
--   1) есть ли у героя отдельный компонент камеры и читается ли он;
--   2) кто владеет поворотом: если у штанги bUsePawnControlRotation = true,
--      она берёт поворот у контроллера и свой относительный поворот
--      игнорирует - тогда наклон надо ставить КАМЕРЕ, а не штанге;
--   3) держится ли записанный поворот или игра возвращает своё - то есть
--      будет ли это опять покадровая драка.
--
-- Только чтение. Пишет ТОЛЬКО отдельная команда probe = pitch:<число>.
local function probe_camera_angle()
    if not (arm and arm:IsValid()) then
        say("разведка наклона: штанги ещё нет"); return
    end
    local owner
    if not pcall(function() owner = arm:GetOwner() end) or not (owner and owner:IsValid()) then
        say("разведка наклона: у штанги нет хозяина"); return
    end

    say("=== РАЗВЕДКА НАКЛОНА ===")
    say("штанга: %s", tostring(arm_name))
    local flags = { "bUsePawnControlRotation", "bInheritPitch", "bInheritYaw",
                    "bInheritRoll", "bDoCollisionTest", "bEnableCameraLag" }
    for _, f in ipairs(flags) do
        local v
        if pcall(function() v = arm[f] end) and v ~= nil then
            say("  штанга.%s = %s", f, tostring(v))
        end
    end
    local rr
    pcall(function() rr = arm.RelativeRotation end)
    if rr then
        say("  штанга.RelativeRotation  Pitch=%s Yaw=%s Roll=%s",
            tostring(rr.Pitch), tostring(rr.Yaw), tostring(rr.Roll))
    end

    local cam
    pcall(function() cam = owner.CameraThirdPerson end)
    if cam and cam:IsValid() then
        say("камера: %s", cam:GetFullName())
        local v
        if pcall(function() v = cam.bUsePawnControlRotation end) and v ~= nil then
            say("  камера.bUsePawnControlRotation = %s", tostring(v))
        end
        if pcall(function() v = cam.FieldOfView end) and v ~= nil then
            say("  камера.FieldOfView = %s", tostring(v))
        end
        local cr
        pcall(function() cr = cam.RelativeRotation end)
        if cr then
            say("  камера.RelativeRotation  Pitch=%s Yaw=%s Roll=%s",
                tostring(cr.Pitch), tostring(cr.Yaw), tostring(cr.Roll))
        else
            say("  камера.RelativeRotation НЕ ЧИТАЕТСЯ")
        end
    else
        say("камера: CameraThirdPerson не читается - имя компонента другое")
    end
    say("=== КОНЕЦ РАЗВЕДКИ ===")
end

-- Пробная запись наклона. ОТДЕЛЬНОЙ КОМАНДОЙ и с ОБРАТНЫМ ЧТЕНИЕМ через
-- полторы секунды: «запись прошла» и «значение держится» - разные утверждения,
-- и путать их этот проект уже оплатил (EXP-0071).
-- Свойство RelativeRotation пишется НЕ присваиванием: в Unreal присваивание
-- не помечает трансформацию грязной, и поворот молча не применится. Поэтому
-- зовём K2_SetRelativeRotation - штатный путь, тот же, которым пользуется
-- блюпринт.
local function probe_pitch_write(deg)
    if not (arm and arm:IsValid()) then say("наклон: штанги нет"); return end
    local owner
    if not pcall(function() owner = arm:GetOwner() end) or not (owner and owner:IsValid()) then
        say("наклон: у штанги нет хозяина"); return
    end
    local cam
    pcall(function() cam = owner.CameraThirdPerson end)
    if not (cam and cam:IsValid()) then say("наклон: камеры нет"); return end

    local wrote = pcall(function()
        cam:K2_SetRelativeRotation({ Pitch = deg, Yaw = 0.0, Roll = 0.0 },
                                   false, {}, false)
    end)
    say("наклон: записал Pitch=%.1f (%s)", deg, wrote and "вызов прошёл" or "ВЫЗОВ НЕ УДАЛСЯ")

    ExecuteInGameThreadWithDelay(1500, function()
        ExecuteInGameThread(function()
            local cr
            pcall(function() cr = cam.RelativeRotation end)
            if cr then
                say("наклон: через 1.5 с в камере Pitch=%s (просили %.1f)",
                    tostring(cr.Pitch), deg)
            else
                say("наклон: обратное чтение не удалось")
            end
        end)
    end)
end

-- ============= КАНАЛ УПРАВЛЕНИЯ БЕЗ КЛАВИШ (agent-cmd.txt) =============
--
-- ЗАЧЕМ. 10.09.2026 замером установлено: агент НЕ МОЖЕТ нажать ни одной
-- клавиши этого мода. Tab до игры доходит (инвентарь открывается), а Numpad и
-- Ctrl+Numpad до UE4SS - нет: ни виртуальной клавишей, ни скан-кодом, ни при
-- удержании 300 мс, при включённом NumLock и игре в фокусе. Значит каждый
-- камерный опыт агента «с нумпада» был холостым ходом, а слово «проверил» -
-- неправдой. Клавиша, которую харнесс нажать не может, не проверяется никем.
--
-- ЭТО НЕ config.lua, И ЭТО ОСОЗНАННО: мод сам переписывает config.lua
-- автосохранением, и общий файл дал бы петлю «мод пишет - видит чужое
-- изменение - применяет заново».
--
-- Формат: по строке на команду, пустые строки и `--` игнорируются.
--     offset_z = 80
--     logging_enabled = false
--     probe = angle
--     probe = pitch:-10
local CMD_PATH = SCRIPT_DIR .. "../agent-cmd.txt"
local cmd_seen = nil

local function run_cmd_body(body)
    -- BOM СНИМАЕМ ПЕРВЫМ ДЕЛОМ. Оплачено 10.09.2026: Windows PowerShell 5.1
    -- с `-Encoding utf8` пишет файл С МЕТКОЙ ПОРЯДКА БАЙТ (EF BB BF), и первая
    -- строка перестаёт совпадать с шаблоном - канал молчит, файл при этом на
    -- вид правильный. Ровно тот же класс, что и «ключ пропал из config.lua»:
    -- отказ без единой строки в журнале.
    body = body:gsub("^\239\187\191", "")
    local touched, want_distance = 0, false
    for line in body:gmatch("[^\r\n]+") do
        local k, v = line:match("^%s*([%w_]+)%s*=%s*(.-)%s*$")
        if k and v and k ~= "" then
            if k == "probe" then
                if v == "angle" then
                    probe_camera_angle()
                else
                    local deg = v:match("^pitch:(-?%d+%.?%d*)$")
                    if deg then
                        probe_pitch_write(tonumber(deg))
                    else
                        say("agent-cmd: не знаю разведку %q", v)
                    end
                end
            elseif cfg[k] == nil then
                say("agent-cmd: нет такой настройки: %s", k)
            else
                local cur = cfg[k]
                local ok = true
                if type(cur) == "boolean" then
                    cfg[k] = (v == "true")
                elseif type(cur) == "number" then
                    local n = tonumber(v)
                    if n then cfg[k] = n
                    else ok = false; say("agent-cmd: %s ждёт число, пришло %q", k, v) end
                else
                    cfg[k] = v
                end
                if ok then
                    touched = touched + 1
                    say("agent-cmd: %s = %s", k, tostring(cfg[k]))
                    if k == "arm_length" then want_distance = true end
                end
            end
        end
    end
    if touched > 0 then
        apply(want_distance)
        if want_distance then desired_zoom = cfg.arm_length end
        say("agent-cmd: применено настроек: %d", touched)
    end
end

local function poll_agent_cmd()
    local f = io.open(CMD_PATH, "r")
    if not f then return end
    local body = f:read("*a")
    f:close()
    if not body or body == cmd_seen then return end
    -- Первое чтение после старта тоже исполняем: файл мог быть положен до
    -- запуска игры, и «пропустить, потому что не видели прежнего» означало бы
    -- ровно то молчание, от которого этот канал и заводится.
    cmd_seen = body
    ExecuteInGameThread(function() pcall(run_cmd_body, body) end)
end

if type(LoopInGameThreadWithDelay) == "function" then
    -- РАЗ В СЕКУНДУ, А НЕ ЧАЩЕ. Холостой таймер на игровом потоке уже клал в
    -- очередь UE4SS 60 заданий в секунду и вместе со сторожем довёл игру до
    -- падения (разбор у target_recheck_ms). Секунды хватает: это канал для
    -- опытов, а не для управления в бою.
    LoopInGameThreadWithDelay(1000, function() pcall(poll_agent_cmd) end)
