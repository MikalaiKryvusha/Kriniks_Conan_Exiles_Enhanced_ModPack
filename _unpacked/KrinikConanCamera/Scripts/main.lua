-- Дистанция на плюсе и минусе, как громкость
local function change_arm(delta)
    return function()
        if cfg.arm_length < 0 and arm and arm:IsValid() then
            cfg.arm_length = arm.TargetArmLength      -- перехватываем штатную
        end
        cfg.arm_length = math.max(0, cfg.arm_length + delta)
        -- Просим ИМЕННО дистанцию - и тут же объявляем её желаемой, иначе
        -- сторож зума через миг вернёт ту, что была накручена колесом.
        apply(true)
        desired_zoom = cfg.arm_length
        log("дистанция = %.1f", cfg.arm_length)
        schedule_autosave()
    end
end
