local last_mute_check = 0

local function mute_one(c, cname)
    local on = nil
    -- ⚠️ ОТКАЗ ЧТЕНИЯ И "ТИК УЖЕ ВЫКЛЮЧЕН" - РАЗНЫЕ ФАКТЫ. Если их не различать,
    -- неработающая глушилка выглядит как сделавшая своё дело: молчание в обоих
    -- случаях одинаковое (EXP-0072 - тишина как признак).
    if not pcall(function() on = c:IsComponentTickEnabled() end) then
        mute_fail = mute_fail + 1
        if mute_fail <= 3 then
            log("глушение %s: прочитать состояние тика не удалось", cname)
        end
        return
    end
    if on == false then return end          -- уже тихо: писать нечего

    local ok = pcall(function() c:SetComponentTickEnabled(false) end)
    -- ⚠️ ОБРАТНОЕ ЧТЕНИЕ ОБЯЗАТЕЛЬНО. "Запись прошла" не равно "значение
    -- держится" - за это правило заплачено полем NewTargetArmLength, куда
    -- запись проходила успешно и тут же затиралась игрой (баг 09).
    local after = nil
    pcall(function() after = c:IsComponentTickEnabled() end)
    if after == false then
        mute_hits = mute_hits + 1
        if mute_hits <= 6 or mute_hits % 25 == 0 then
            log("чужая камера заглушена: %s (раз %d)", cname, mute_hits)
        end
    else
        mute_fail = mute_fail + 1
        if mute_fail <= 3 then
            log("глушение %s НЕ ДЕРЖИТСЯ: запись %s, тик после неё %s",
                cname, ok and "прошла" or "отказала", tostring(after))
        end
    end
end

