    log("  CurrentCameraMode = %s", tostring(mode))

    local tbl
    if not pcall(function() tbl = owner.CustomCamModeSettings end) or tbl == nil then
        log("  CustomCamModeSettings не прочиталось"); return
    end
    log("  тип значения: %s", type(tbl))

    local n
    if pcall(function() n = tbl:GetArrayNum() end) and type(n) == "number" then
        log("  это массив, элементов: %d", n)
        for i = 1, math.min(n, 10) do
            local el
            if pcall(function() el = tbl[i] end) and el ~= nil then
                local found = false
                for _, f in ipairs({ "SocketOffset", "CameraSocketOffset", "Offset",
                                     "SpringArmSocketOffset", "TargetOffset",
                                     "LocationOffset", "ArmLength", "TargetArmLength" }) do
                    local v
