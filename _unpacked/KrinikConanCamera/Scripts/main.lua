-- (obj[name] по объектному свойству, EXCEPTION_ACCESS_VIOLATION 0x7378), а
-- перечисление ИМЁН И ТИПОВ значений не трогает вовсе. Полное имя свойства в
-- Unreal начинается с его класса - ArrayProperty / MapProperty / StructProperty
-- и так далее, - поэтому одного GetFullName() достаточно, чтобы понять, чем на
-- самом деле является таблица режимов и как в неё писать.
local function probe_types()
    log("---- ТИПЫ КАМЕРНЫХ СВОЙСТВ ПЕРСОНАЖА (без чтения значений) ----")
    if not (arm and arm:IsValid()) then log("  штанги нет"); return end
    local owner
    if not pcall(function() owner = arm:GetOwner() end) or not (owner and owner:IsValid()) then
        log("  персонажа нет"); return
    end
    local cls
    if not pcall(function() cls = owner:GetClass() end) or not cls then
        log("  класс не получен"); return
    end
    local shown = 0
    local ok = pcall(function()
        cls:ForEachProperty(function(prop)
            local full
            if not pcall(function() full = prop:GetFullName() end) or not full then return end
            local low = full:lower()
            if low:find("cam") or low:find("modesettings") or low:find("armlength") then
                shown = shown + 1
                if shown <= 60 then log("  %s", full) end
            end
        end)
    end)
    if not ok then log("  перечисление свойств не поддержано этой сборкой UE4SS")
    else log("  всего подходящих свойств: %d", shown) end
    log("---- КОНЕЦ ----")
end

