-- ⚠️ zoom_cap_hits здесь БОЛЬШЕ НЕ ОБЪЯВЛЯЕТСЯ: он живёт наверху файла, выше
-- всех мест использования. Второе объявление здесь было бы не безобидным
-- дублем, а ловушкой - оно перекрывало бы верхнее только для кода НИЖЕ себя, и
-- два счётчика с одним именем считали бы разное.

-- Кто сколько раз сработал. Это главный прибор этой правки: «встал» ничего не
-- значит, значение имеет только «сработал».
local zoom_fires = {}

local function clamp_zoom_now(tag, ctx)
    zoom_fires[tag] = (zoom_fires[tag] or 0) + 1
    if zoom_fires[tag] <= 2 then
        say("перехват СРАБОТАЛ: %s (вызов %d)", tag, zoom_fires[tag])
    end
    local hi = (type(cfg.zoom_max) == "number") and cfg.zoom_max or -1
    if hi <= 0 then return end
    local ch
    if not pcall(function() ch = ctx:get() end) or not ch then return end
    local nz
    if not pcall(function() nz = ch.NewTargetArmLength end) or type(nz) ~= "number" then return end
    if nz <= hi + 0.5 then return end
    pcall(function() ch.NewTargetArmLength = hi end)
    -- ⚠️ ЧИТАЕМ ОБРАТНО. Без этого «зажал» - вера, а не факт: за вечер уже
    -- дважды оказывалось, что запись проходит без ошибки и ни на что не влияет.
    local back
    pcall(function() back = ch.NewTargetArmLength end)
    zoom_cap_hits = zoom_cap_hits + 1
    if zoom_cap_hits <= 5 or zoom_cap_hits % 50 == 0 then
        log("предел (%s): просили %.1f - записали %.1f - в поле теперь %s (раз %d)",
            tag, nz, hi, tostring(back), zoom_cap_hits)
    end
end

-- ⚠️ ВЕШАЕМ ПОЗЖЕ ЗАГРУЗКИ МОДА, И ЭТО ИЗМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО.
-- Первая редакция вешала перехват сразу при загрузке. Журнал 09.09.2026
-- 23:37:27: «перехват зума не встал» по ОБОИМ написаниям пути, и следом
-- «предела отдаления сейчас НЕТ». Причина простая: в этот момент игра ещё в
-- меню, класс BasePlayerChar_C не загружен, и вешать хук не на что.
-- Поэтому установка вызывается из события появления персонажа, а если и там
-- не вышла - повторяется, пока не встанет.
local zoom_hook_path = nil
local zoom_hook_tries = 0

-- ⚠️ ВЕШАЕМ НА ВСЕ КАНДИДАТЫ, А НЕ НА ПЕРВЫЙ УДАЧНЫЙ.
-- Оплачено 09.09.2026 23:51: перехват «встал» на CameraZoomOut - и не
-- сработал НИ РАЗУ, пока цель уходила на 3820. RegisterHook не возвращает
-- ошибку на функцию блюпринта, которую в итоге никто не вызывает, поэтому
-- «встал» и «срабатывает» - РАЗНЫЕ утверждения, и первое ничего не доказывает.
-- Цикл, останавливавшийся на первом успехе, из-за этого так и не добрался до
-- события ввода InpActEvt_ZoomOut - а именно события блюпринта хукаются
-- надёжнее всего. Теперь вешаем на все и СЧИТАЕМ СРАБАТЫВАНИЯ по каждому:
-- журнал сам назовёт того, через кого на самом деле идёт колесо.
try_install_zoom_hook = function()
    -- Перехват шеи от первого лица — здесь же: сюда доходят, когда класс героя уже загружен (подписка на появление
    -- героя в этой сборке не срабатывает — прогон 2026-10-29 10:52: перехват зума встал, строки о шее не было). [NOT-TESTED]
    pcall(install_fp_neck_hooks)
    if zoom_hook_path then return end
    zoom_hook_tries = zoom_hook_tries + 1
    local installed = {}
    for _, p in ipairs(ZOOM_FN_CANDIDATES) do
        -- Сперва форма с ДВУМЯ колбэками (до и после): зажимать надо результат,
        -- а он есть только ПОСЛЕ вызова. Если сборка UE4SS такой формы не знает,
        -- берём двухаргументную - ту, которой этот же мод уже вешает удержание,
        -- то есть заведомо рабочую здесь.
        local tag = p:match("([^:]+)$") or p
        local ok = pcall(function()
            RegisterHook(p, function() end, function(ctx) pcall(clamp_zoom_now, tag, ctx) end)
        end)
        if not ok then
            ok = pcall(function()
                RegisterHook(p, function(ctx) pcall(clamp_zoom_now, tag, ctx) end)
            end)
        end
        if ok then installed[#installed + 1] = tag
        else log("перехват зума не встал (попытка %d): %s", zoom_hook_tries, p) end
    end

    if #installed > 0 then
        zoom_hook_path = table.concat(installed, ", ")
        -- Печатаем МИМО logging_enabled: «предела нет» и «предел молча не
        -- встал» выглядят одинаково, а лечатся по-разному.
        say("предел отдаления %.0f: перехваты стоят на %s (попытка %d)",
            (type(cfg.zoom_max) == "number") and cfg.zoom_max or -1,
            zoom_hook_path, zoom_hook_tries)
        -- ⚠️ ПРОВЕРЯЕМ НЕ УСТАНОВКУ, А РАБОТУ. Через полминуты скажем вслух,
        -- сработал ли хоть один: молчащий перехват - главная ловушка этого
        -- вечера, и обнаружить её должен мод, а не владелец.
        ExecuteInGameThreadWithDelay(30000, function()
            local total = 0
            for _, n in pairs(zoom_fires) do total = total + n end
            if total == 0 then
                say("ВНИМАНИЕ: перехваты зума стоят, но НЕ СРАБОТАЛИ ни разу за 30 секунд")
            end
        end)
        return
    end

    -- Повторяем: класс мог ещё не догрузиться. Пять попыток по три секунды -
    -- это пятнадцать секунд, дольше любой загрузки мира на этой машине.
    if zoom_hook_tries < 5 then
        ExecuteInGameThreadWithDelay(3000, function() pcall(try_install_zoom_hook) end)
    else
        say("ВНИМАНИЕ: перехват зума НЕ встал за %d попыток - предела отдаления НЕТ",
            zoom_hook_tries)
    end
end

