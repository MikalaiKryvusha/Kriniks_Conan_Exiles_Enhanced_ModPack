local function cam_push_for(pitch)
    if pitch <= CAM_PUSH_FROM then return 0 end
    if pitch >= CAM_PUSH_FULL then return CAM_PUSH_CM end
    return CAM_PUSH_CM * (pitch - CAM_PUSH_FROM) / (CAM_PUSH_FULL - CAM_PUSH_FROM)
end
