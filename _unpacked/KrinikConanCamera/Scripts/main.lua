local EFFECT_CLASSES = { "NiagaraComponent", "ParticleSystemComponent",
                         "ExponentialHeightFog", "SkyAtmosphere",
                         "SceneCaptureComponent2D" }
local RAIN_HINTS = { "rain", "weather", "precip", "storm", "snow", "drop", "scenecapture" }

-- ШУМ, КОТОРЫЙ СЪЕДАЛ ВЫДАЧУ. Слово "storm" стоит в имени песчаной бури из
-- ВСТУПИТЕЛЬНОГО РОЛИКА, а её экземпляров три десятка - они висят в памяти всю
-- сессию и забивали показ целиком. 09.09.2026 зонд нажали дважды, в том числе
-- во время НАСТОЯЩЕГО дождя, и оба раза он показал одну песчаную бурю: потолок
-- показа стоял на 12, а совпадений было 31. Прибор нашёл, но не показал -
-- худший вид отказа, потому что выглядит как ответ.
local RAIN_SKIP = { "openingcinematic", "charactercreation", "moviescene" }
local RAIN_SHOW_MAX = 40

local function probe_rain()
    say("---- РАЗВЕДКА ДОЖДЯ (только имена) ----")
    for _, cls in ipairs(EFFECT_CLASSES) do
        local list = FindAllOf(cls)
        if list and #list > 0 then
            local hits, shown, skipped = 0, 0, 0
            for _, o in ipairs(list) do
                if o:IsValid() then
                    local name = o:GetFullName()
                    local low = name:lower()
                    for _, hint in ipairs(RAIN_HINTS) do
                        if low:find(hint, 1, true) then
                            hits = hits + 1
                            local noise = false
                            for _, bad in ipairs(RAIN_SKIP) do
                                if low:find(bad, 1, true) then noise = true break end
                            end
                            if noise then
                                skipped = skipped + 1
                            elseif shown < RAIN_SHOW_MAX then
                                shown = shown + 1
                                say("  [%s] %s", cls, name:sub(-90))
                            end
                            break
                        end
                    end
                end
            end
            say("  класс %s: всего %d, похожих на погоду %d, из них ролик %d, показано %d",
                cls, #list, hits, skipped, shown)
        else
            say("  класс %s: не найдено", cls)
        end
    end
    -- ВТОРАЯ СТАДИЯ (ГЛАВНАЯ): ЧИСЛА САМОЙ СИСТЕМЫ ЧАСТИЦ.
    --
    -- ЗАЧЕМ. Съёмка дождя (ниже) НЕ управляет его дальностью - это опровергнуто
    -- измерением 09.09.2026: владелец переключал OrthoWidth двенадцать раз, и
    -- картинка не менялась ни разу. Настоящая цель - Niagara-система осадков,
    -- найденная этим же зондом 10.09.2026 в живом дожде:
    --     PersistentLevel.BP_Dynamic_Weather_Siptah_Rain_C....NS_Precipitation
    -- Дальность дождя у Niagara задают две вещи: коробка спавна и ФИКСИРОВАННЫЕ
    -- границы системы (пересчитывать их каждый тик при тысячах частиц дорого,
    -- поэтому их приколачивают). Край коробки и есть то, что владелец видит как
    -- «дождь появляется из воздуха».
    --
    -- ⚠️ СНАЧАЛА ИМЕНА, ПОТОМ ЗНАЧЕНИЯ. Перебор чужих свойств вслепую уронил
    -- игру трижды 08.09.2026. Поэтому печатаем СПИСОК свойств класса (это
    -- метаданные, читать их безопасно), и отдельно пробуем прочитать те поля,
    -- что известны по документации Unreal, - каждое в своём pcall.
    local nias
    if pcall(function() nias = FindAllOf("NiagaraComponent") end) and nias then
        for _, c in ipairs(nias) do
            local nm
            if pcall(function() nm = c:GetFullName() end) and nm
               and nm:lower():find("precip", 1, true) then
                say("---- ЧИСЛА СИСТЕМЫ ОСАДКОВ ----")
                say("  объект: %s", nm)

                -- Значения известных поимённо полей.
                for _, f in ipairs({ "bOverrideBounds", "bAutoActivate", "bIsActive",
                                     "BoundsScale", "MaxTimeBeforeForceUpdateTransform",
                                     "bRenderingEnabled", "AgeUpdateMode", "SeekDelta",
                                     "bAllowScalability", "TickBehavior" }) do
                    local v
                    if pcall(function() v = c[f] end) and v ~= nil then
                        say("  %s = %s", f, tostring(v))
                    end
                end

                -- Границы и масштаб - структуры, печатаем покоординатно.
                local fb
                if pcall(function() fb = c.FixedBounds end) and fb then
                    local ok, txt = pcall(function()
                        return ("Min X=%.0f Y=%.0f Z=%.0f | Max X=%.0f Y=%.0f Z=%.0f")
                            :format(fb.Min.X, fb.Min.Y, fb.Min.Z, fb.Max.X, fb.Max.Y, fb.Max.Z)
                    end)
                    say("  FixedBounds = %s", ok and txt or tostring(fb))
                end
                for _, f in ipairs({ "RelativeScale3D", "RelativeLocation" }) do
                    local v
                    if pcall(function() v = c[f] end) and v ~= nil then
                        local ok, txt = pcall(function()
                            return ("X=%.1f Y=%.1f Z=%.1f"):format(v.X, v.Y, v.Z)
                        end)
                        say("  %s = %s", f, ok and txt or tostring(v))
                    end
                end

                -- ПОЛНЫЙ СПИСОК ИМЁН - чтобы следующий заход читал значения
                -- адресно, а не гадал. Только имена и типы, значений не трогаем.
                say("  --- свойства класса (имя : тип) ---")
                local cls, shown = nil, 0
                pcall(function() cls = c:GetClass() end)
                if cls then
                    pcall(function()
                        cls:ForEachProperty(function(prop)
                            if shown >= 140 then return end
                            local n, t
                            pcall(function()
                                n = prop:GetFName():ToString()
                                t = prop:GetClass():GetFName():ToString()
                            end)
                            if n then
                                shown = shown + 1
                                say("    %s : %s", n, tostring(t))
                            end
                        end)
                    end)
                    say("  свойств показано: %d", shown)
                end

                -- Владелец компонента - актёр погоды. Его свойства тоже нужны:
                -- коробка спавна может задаваться на нём, а не на компоненте.
                local owner
                if pcall(function() owner = c:GetOwner() end) and owner and owner:IsValid() then
                    local on
                    pcall(function() on = owner:GetFullName() end)
                    say("  --- актёр-владелец: %s ---", tostring(on))
                    local ocls, oshown = nil, 0
                    pcall(function() ocls = owner:GetClass() end)
                    if ocls then
                        pcall(function()
                            ocls:ForEachProperty(function(prop)
                                if oshown >= 140 then return end
                                local n, t
                                pcall(function()
                                    n = prop:GetFName():ToString()
                                    t = prop:GetClass():GetFName():ToString()
                                end)
                                if n then
                                    oshown = oshown + 1
                                    say("    %s : %s", n, tostring(t))
                                end
                            end)
                        end)
                        say("  свойств актёра показано: %d", oshown)
                    end
                end
                say("---- КОНЕЦ ЧИСЕЛ ОСАДКОВ ----")
                break
            end
        end
    end

    -- ТРЕТЬЯ СТАДИЯ: ЧИСЛА СЪЁМКИ ДОЖДЯ.
    -- Weather_SceneCapture2d_Rain - обычный движковый SceneCaptureComponent2D,
    -- и его поля ДОКУМЕНТИРОВАНЫ Epic. Это не перебор чужих свойств вслепую
    -- (тот уронил игру трижды 08.09.2026), а чтение ИЗВЕСТНЫХ ПОИМЁННО полей,
    -- каждое в своём pcall. Ради них всё и затевалось: OrthoWidth - охват
    -- съёмки по горизонтали, высота - положение над игроком. Именно их границы
    -- владелец видит как "дождь появляется из воздуха".
    local caps
    if pcall(function() caps = FindAllOf("SceneCaptureComponent2D") end) and caps then
        for _, c in ipairs(caps) do
            local nm
            if pcall(function() nm = c:GetFullName() end) and nm
               and nm:lower():find("rain", 1, true) then
                say("---- ЧИСЛА СЪЁМКИ ДОЖДЯ ----")
                for _, f in ipairs({ "OrthoWidth", "ProjectionType", "CaptureSource",
                                     "FOVAngle", "MaxViewDistanceOverride",
                                     "bCaptureEveryFrame", "bCaptureOnMovement" }) do
                    local v
                    if pcall(function() v = c[f] end) and v ~= nil then
                        say("  %s = %s", f, tostring(v))
                    else
                        say("  %s - прочитать не удалось", f)
                    end
                end
                -- Положение: сперва мировое, потом относительное. Оба - штатные
                -- поля USceneComponent, оба печатаются покоординатно.
                for _, f in ipairs({ "RelativeLocation" }) do
                    local v
                    if pcall(function() v = c[f] end) and v ~= nil then
                        local ok, txt = pcall(function()
                            return ("X=%.1f Y=%.1f Z=%.1f"):format(v.X, v.Y, v.Z)
                        end)
                        say("  %s = %s", f, ok and txt or tostring(v))
                    else
                        say("  %s - прочитать не удалось", f)
                    end
                end
                local loc
                if pcall(function() loc = c:K2_GetComponentLocation() end) and loc then
                    local ok, txt = pcall(function()
                        return ("X=%.1f Y=%.1f Z=%.1f"):format(loc.X, loc.Y, loc.Z)
                    end)
                    say("  мировое положение = %s", ok and txt or tostring(loc))
                end
                say("---- КОНЕЦ ЧИСЕЛ ----")
            end
        end
    end

    pcall(apply_rain_ortho, true)
    say("---- КОНЕЦ РАЗВЕДКИ ДОЖДЯ ----")
end

-- ============ ШИРИНА ДОЖДЯ ============
--
-- ЗАКАЗ владельца 09.09.2026: "дождь появляется из воздуха на больших
-- отдалениях камеры". Замер того же дня назвал причину числом: у съёмки
-- Weather_SceneCapture2d_Rain охват OrthoWidth = 4096, то есть 41 x 41 метр
-- вокруг игрока - вся область, где игра знает, куда дождю падать. За её краем
-- маска не определена, и этот край владелец и видит.
--
-- ⚠️ ЦЕНА, НАЗВАННАЯ ДО ПРАВКИ. Текстура маски (Weather_RenderTarget_Rain)
-- своего размера не меняет. Значит втрое больший охват = втрое грубее маска на
-- метр. Признак перебора виден глазом: дождь начнёт протекать под навесы и
-- кроны, потому что маска перестанет их разрешать. Если так - уменьшать.
--
-- 0 или отрицательное в конфиге = НЕ ТРОГАТЬ (поведение по умолчанию для чужой
-- сборки: мы правим ЧУЖОЙ объект игры, и молчаливым это быть не должно).
local rain_ortho_done = false

-- Периодическая проверка: съёмка появляется и исчезает вместе с погодой.
-- 5000 мс - компромисс: дождь идёт минутами, а FindAllOf по классу не бесплатен.
rain_watch_chain = function()
    ExecuteInGameThreadWithDelay(5000, function()
        ExecuteInGameThread(function() pcall(apply_rain_ortho, false) end)
        if type(rain_watch_chain) == "function" then rain_watch_chain() end
    end)
end

apply_rain_ortho = function(force)
    local want = cfg.rain_ortho_width
    if type(want) ~= "number" or want <= 0 then return end
    if rain_ortho_done and not force then return end

    local caps
    if not pcall(function() caps = FindAllOf("SceneCaptureComponent2D") end)
       or not caps or #caps == 0 then
        -- Съёмки нет - значит дождь кончился и объект уничтожен. Сбрасываем
        -- отметку "уже применили": следующий дождь создаст НОВЫЙ объект с
        -- ванильной шириной, и его надо будет расширить заново.
        rain_ortho_done = false
        return
    end
    for _, c in ipairs(caps) do
        local nm
        if pcall(function() nm = c:GetFullName() end) and nm
           and nm:lower():find("rain", 1, true) then
            local was
            pcall(function() was = c.OrthoWidth end)
            local ok = pcall(function() c.OrthoWidth = want end)
            local now
            pcall(function() now = c.OrthoWidth end)
            if ok and now and math.abs(now - want) < 1.0 then
                rain_ortho_done = true
                say("дождь: охват съёмки %.0f -> %.0f (%.0f м вместо %.0f м)",
