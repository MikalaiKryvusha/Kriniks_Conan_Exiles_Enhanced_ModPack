    log("  камер у персонажа: %d из %d в мире", mine, #cams)

    -- 2. Что говорит сама штанга помимо смещения
    if arm and arm:IsValid() then
        pcall(function()
            log("  ШТАНГА: TargetArmLength=%.1f", arm.TargetArmLength)
            local to = arm.TargetOffset
            log("      TargetOffset X=%.1f Y=%.1f Z=%.1f", to.X, to.Y, to.Z)
            log("      bUsePawnControlRotation=%s bDoCollisionTest=%s bEnableCameraLag=%s",
