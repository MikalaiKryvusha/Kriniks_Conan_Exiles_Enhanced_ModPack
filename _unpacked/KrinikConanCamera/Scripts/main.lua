--[[============================================================================
  KrinikConanCamera (until 2026-10-31 ConanCameraControl) — камера строго за спиной для Conan Exiles Enhanced
  ============================================================================

  ЗАЧЕМ. В Конане третьеличная камера смотрит из-за плеча. Владельцу нужна
  камера ПО ЦЕНТРУ за головой — то же, что уже настроено в Palworld модом
  CameraControl (Nexus 3659), где ключевое значение offset_y = 0.

  ГОТОВОГО МОДА НЕТ. Проверено исчерпывающе: Nexus (все 40 модов Enhanced),
  Steam Workshop, ModDB, GitHub. Разбор — docs/04-камера.md в этом паке.

  КУДА ПИШЕМ. Не в палворлдовские свойства CameraBoom (их в Конане нет), а в
  штатные свойства USpringArmComponent:
      SocketOffset.X  — назад/вперёд (отрицательное = камера дальше назад)
      SocketOffset.Y  — вбок. НОЛЬ = строго за спиной. Это и есть требование
      SocketOffset.Z  — высота
      TargetArmLength — длина «палки», то есть дистанция
  Маршрут взят у практиков, а не придуман: так делают MMOCams и живой
  Enhanced-мод 3rdCamDist Кхарзетта (github.com/Kharzette/ConanMods).

  ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА: НЕ ГАДАТЬ ОБ ИМЕНАХ.
  Серверный дамп подсказывает имя ThirdPersonSpringArm, но снят он на ДРУГОМ
  билде и на СЕРВЕРЕ. Поэтому мод сперва находит все SpringArm в мире, печатает
  их полные имена, и только потом выбирает. Если выбор ошибочен — в журнале
  видно, из чего он выбирал, и config.lua позволяет назвать компонент вручную.

  ЧЕГО МЫ НЕ ЗНАЕМ (честно, до первого запуска):
   * заведётся ли UE4SS на этом билде (CL-373655) — никем не
     подтверждено;
   * как называется компонент камеры на КЛИЕНТЕ;
   * не возвращает ли игра камеру сама каждый кадр. Автор 3rdCamDist снял свою
     горячую клавишу со словами «funcom now recenters the camera if it ever
     drifts» — поэтому здесь есть повторное применение по таймеру, и его можно
     выключить в config.lua, если окажется не нужным;
   * центровка камеры, по словам и MMOCams, и Кхарзетта, ЛОМАЕТ СТРЕЛЬБУ ИЗ
     ЛУКА. Это ожидаемая плата, а не дефект мода.
============================================================================]]

