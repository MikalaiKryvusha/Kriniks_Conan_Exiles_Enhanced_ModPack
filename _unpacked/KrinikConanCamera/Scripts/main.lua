local function keep_target_body()
    -- Глушение чужой камеры - ПЕРВЫМ и до любого возврата ниже: оно не зависит
    -- ни от того, взяли ли мы штангу, ни от того, владеем ли целью. Иначе в
    -- меню и в первые секунды мира оно бы не работало вовсе.
    pcall(mute_foreign_camera)

    -- ⚠️ ВОССТАНОВЛЕНИЕ ПОСЛЕ СМЕРТИ. При возрождении игра создаёт НОВОГО
    -- персонажа, и наша штанга становится недействительной. Без этой ветки мод
    -- молча замолкал: возвращать цель было некому, и камера уходила за плечо -
    -- владелец увидел это как "после смерти и перерождения камера скинулась".
    -- Пробуем взять камеру заново, не чаще раза в секунду.
    if not (arm and arm:IsValid()) then
        -- ⚠️ РАЗНАЯ ЦЕНА У ДВУХ ОДИНАКОВЫХ НА ВИД СЛУЧАЕВ (правка 09.09.2026).
        -- "Камеры нет" бывает двух родов, и путать их дорого:
        --   * мы её УЖЕ имели и потеряли (смерть, возрождение) - вернуть надо
        --     быстро, владелец эту скорость проверил и она ему видна;
        --   * мы её НЕ ИМЕЛИ НИ РАЗУ - это главное меню, где камеры нет по
        --     определению, и частый пересбор там бесполезен целиком.
        -- Раньше оба случая шли раз в секунду, и в меню это давало полный
        -- пересбор компонентов каждую секунду ПЛЮС свою цепочку поиска. Игра
        -- оборвалась (Abort signal) на 39-й, 96-й и 267-й секунде стояния в
        -- меню; с выключенным модом 200 секунд прошли без обрыва.
        local now = os.clock()
        local gap = ever_adopted and 1.0 or 5.0
        if now - last_recover >= gap then
            last_recover = now
            target_owned = false
            if rescan then rescan() end
        end
        return
    end

    -- ⚠️ «ЖИВА» И «ТА ЖЕ» - РАЗНЫЕ ВОПРОСЫ. Проверка выше отвечает только на
    -- первый, и на смерти этого мало: мод успевает перецепиться на штангу
    -- камеры смерти, а та остаётся ЖИВОЙ и после возрождения. Пересбор поэтому
    -- не запускался никогда, и настоящая камера персонажа стояла нетронутой -
    -- владелец видел вид из-за плеча (журнал 09.09.2026 23:33:08).
    -- Отцепляемся сразу, как заметили чужого хозяина: дальше сработает ветка
    -- восстановления выше и возьмёт настоящую камеру.
    do
        local an = nil
        pcall(function() an = arm:GetFullName() end)
        if an and an:find(DEAD_CAM_MARK, 1, true) then
            log("держал штангу камеры смерти - отцепляюсь и ищу настоящую")
            arm, arm_name = nil, nil
            target_owned = false
            return
        end
    end

    if not target_owned then return end
    do
        do
            local owner
            if not pcall(function() owner = arm:GetOwner() end) then return end
            if not (owner and owner:IsValid()) then return end
            local cur
            if not pcall(function() cur = owner.TPCameraSocketOffsetTarget end) then return end
            -- ⚠️ ПАДЕНИЕ 2026-10-26 23:13:25 (EXCEPTION_ACCESS_VIOLATION в UE4SS) после выхода в меню и входа в мир: с 23:12:28 цель
            -- читалась мусором, сравнение проваливалось КАЖДЫЙ тик, и сторож 4032 раза за минуту писал зум в объект, чьи поля
            -- читались «TrivialObject» — то есть не в живого героя. Цель не читается числами → ничего не пишем, ищем камеру заново.
            local readable = pcall(function() local _ = cur.X + cur.Y + cur.Z end)
            if not readable then
                if os.clock() - last_recover > 2.0 then
                    last_recover = os.clock()
                    log("сторож: цель камеры не читается (герой сменился?) — запись остановлена, ищу камеру заново")
                    if rescan then pcall(rescan) end
                end
                return
            end
            local same = false
            pcall(function()
                same = math.abs(cur.X - cfg.offset_x) < 0.01
                   and math.abs(cur.Y - cfg.offset_y) < 0.01
                   and math.abs(cur.Z - cfg.offset_z) < 0.01
            end)
            if not same then
                write_pull_target(true)
                pcall(function() apply_zoom_range(owner) end)
                -- Игра только что вернула свою цель (спринт, прицеливание,
                -- верхом). Камера сейчас ЗАКОННО не на месте: её ведёт
                -- интерполяция игры, и на дорогу нужно время. Даём полторы
                -- секунды тишины сторожу.
                target_grace_until = os.clock() + 1.5
                target_miss_since = 0
            end

            -- СТОРОЖ ЛЕЧЕНИЯ. Всякая починка обязана рождать проверку, иначе
            -- "работает" остаётся верой. Если цель наша, а камера всё равно не
            -- там - значит игра держит смещение не только целью, и лечение
            -- неполно. Три промаха подряд (три секунды) - честно возвращаемся
            -- на старое удержание, чтобы владелец не остался с камерой из-за
            -- плеча, и говорим об этом в журнал.
            -- ЗАМЕР ЗУМА раз в секунду: три числа разом, чтобы увидеть, какое
            -- из них игра сбрасывает на прыжке, спринте и выходе из FPV.
            -- Тем же способом (замер вместо догадок) была найдена причина дрожи.
            if os.clock() - last_zoom_report >= 1.0 then
                last_zoom_report = os.clock()
                local a, nw, df, fov
                pcall(function() a = arm.TargetArmLength end)
                pcall(function() nw = owner.NewTargetArmLength end)
                pcall(function() df = owner.ThirdPersonCameraDefaultTargetArmLength end)
                -- Угол обзора: владелец жалуется на "неприятное отдаление" в
                -- начале спринта, а игры часто делают это НЕ дистанцией, а
                -- расширением FOV - глазом отличить нельзя, числами можно.
                -- Поле CameraThirdPerson у персонажа известно из разведки,
                -- перебирать ничего не нужно.
                pcall(function() fov = owner.CameraThirdPerson.FieldOfView end)
                log("ЗУМ: штанга=%s | цель=%s | ДистанцияВозврата=%s | FOV=%s",
                    tostring(a), tostring(nw), tostring(df), tostring(fov))
            end

            -- ⚠️ УДЕРЖАНИЕ ВСЕГО КАМЕРНОГО НАБОРА, А НЕ ОДНОЙ ЦЕЛИ.
            -- Владелец 08.09.2026: "зум был резкий, но после прыжка опять стал
            -- ватным". Разгадка: игра при смене режима восстанавливает СВОЙ
            -- набор целиком - и цель зума, и границы, и скорость притяжения.
            -- Мы вернули цель, а скорость осталась её (1.0 вместо нашей), и
            -- плавность вернулась вместе с ней. Поэтому сверяем весь набор и
            -- возвращаем своё ТОЛЬКО при расхождении: это не запись 30 раз в
            -- секунду, а редкая правка после чужого сброса.
            -- ПЕРЕМЕННЫЙ ШАГ КОЛЕСА - считается от текущей длины штанги.
            -- Живёт ЗДЕСЬ, а не в apply_zoom_range: тот применяется разово при
            -- выборе компонента, а шаг обязан меняться вслед за дистанцией.
            -- Пишется, как и весь набор ниже, ТОЛЬКО при расхождении - иначе
            -- это была бы запись тридцать раз в секунду вместо чтения.
            local want_step = nil
            if cfg.zoom_step_mid and cfg.zoom_step_mid > 0 then
                local lo, hi = cfg.zoom_min or 60.0, cfg.zoom_max or 1000.0
                local cur_len
                pcall(function() cur_len = arm.TargetArmLength end)
                if cur_len then
                    local near_to = lo + (cfg.zoom_step_near or 5.0) * (cfg.zoom_step_near_count or 2)
                    local far_from = hi - (cfg.zoom_step_far or 40.0) * (cfg.zoom_step_far_count or 10)
                    if (cfg.zoom_step_ratio or 0) > 0 then
                        -- Один закон без стыка полос (см. zoom_step_ratio в умолчаниях): шаг растёт с дистанцией от ближнего шага.
                        -- От ЦЕЛИ зума, а не от текущей длины: штанга плавно едет к цели, и шаг от неё прыгал 35↔40 на каждом тике
                        -- (2026-10-26 09:56). Округление до сантиметра: до 5 см давало ступеньки 5→10 у самого героя.
                        local base_len = math.max(lo, desired_zoom or cur_len)
                        want_step = math.floor((cfg.zoom_step_near or 5.0) + cfg.zoom_step_ratio * (base_len - lo) + 0.5)
                    elseif cur_len < near_to then
                        want_step = cfg.zoom_step_near
                    elseif cur_len > far_from then
                        want_step = cfg.zoom_step_far
                    else
                        want_step = cfg.zoom_step_mid
                    end
                end
            elseif cfg.zoom_step and cfg.zoom_step > 0 then
                want_step = cfg.zoom_step
            end
            -- В прицеле лука колесо — выбор стрел Arrow Quick Swap, а не дистанция камеры (раздел «КОЛЕСО В ПРИЦЕЛЕ ЛУКА» выше): шаг родного зума — 0.
            if bow_aim then want_step = 0 end

            local keep = {
                { "TP_SpringArmInterpSpeed",       cfg.zoom_interp_speed },
                { "ThirdPersonCameraMinArmLength", cfg.zoom_min },
                { "ThirdPersonCameraMaxArmLength", cfg.zoom_max },
                { "CameraZoomAmount",              want_step },
            }
            for _, kv in ipairs(keep) do
                local field, want = kv[1], kv[2]
                if want and want >= 0 then
                    -- Шаг меняется ПЛАВНО вслед за дистанцией, поэтому у него
                    -- свой, более грубый порог: с 0.01 запись шла бы почти
                    -- каждый тик, а разницы в полшага глаз не видит.
                    local eps = (field == "CameraZoomAmount") and 1.0 or 0.01
                    local cur
                    if pcall(function() cur = owner[field] end) and cur then
                        if math.abs(cur - want) > eps then
                            local ok = pcall(function() owner[field] = want end)
                            zoom_field_restores = zoom_field_restores + 1
                            if zoom_field_restores <= 6 or zoom_field_restores % 25 == 0 then
                                log("зум: игра вернула своё %s=%.2f - поставил %.2f (раз %d)",
                                    field, cur, want, zoom_field_restores)
                            end
                            if not ok then log("  запись %s не удалась", field) end
                        end
                    end
                end
            end

            -- ⚠️ УДЕРЖАНИЕ ОСИ ВРАЩЕНИЯ СНЯТО 10.09.2026 - И СНЯТО НАСОВСЕМ.
            -- Здесь стояло удержание TargetOffset, заведённое по наблюдению
            -- владельца «она пружинкой назад тянулась». Оно РАБОТАЛО: замер
            -- 17:34 показал 200 удержанных единиц и счётчик, доехавший до 12300.
            -- Убрано не потому, что не работало, а потому, что цена оказалась
            -- больше пользы, и обе половины этого измерены:
            --
            --   1) ЦЕНА. Игра переписывает TargetOffset КАЖДЫЙ КАДР: 12 300
            --      возвратов за семь минут - это 26 записей в секунду. Владелец
            --      увидел результат сразу и назвал его сам: «и дёргалась
            --      камера, когда ты её поднял». Это ровно тот класс дрожи,
            --      который лечил баг 04, только теперь его создавало лечение.
            --
            --   2) ПОЛЬЗЫ НЕТ. Допущение, ради которого поле вообще заводилось
            --      («камера продолжает смотреть в ту же точку, меняется
            --      РАКУРС»), НЕВЕРНО. Заголовок самого Unreal, дословно:
            --      "Offset at start of spring, applied in world space" - это
            --      СДВИГ ВСЕЙ СВЯЗКИ в мировых координатах, поворот в нём не
            --      участвует. Проверено кадром при target_offset_z = 200:
            --      горизонт остался ровно посередине экрана (взгляд не
            --      наклонился ни на градус), а герой уехал за нижний край.
            --      То есть это была вторая ручка ВЫСОТЫ камеры, дублирующая
            --      offset_z на Num 9/3, и ничего сверх неё.
            --
            -- Наклон взгляда даёт ПОВОРОТ КАМЕРЫ, а не сдвиг штанги, и он
            -- держится сам - см. camera_pitch в умолчаниях.
            -- Возвращать удержание оси сюда не надо: сперва перечитать выше.

            -- ====== СТОРОЖ НАКЛОНА С ВЫКЛЮЧАТЕЛЕМ ДРАКИ ======
            --
            -- ЗАЧЕМ ВООБЩЕ. Замер 10.09.2026: после смерти и возрождения игра
            -- создаёт нового персонажа, adopt_arm ставит наклон - и игра
            -- ПОЗЖЕ переписывает его своим значением (обратное чтение дало
            -- Pitch=4.0 вместо нашего). То есть однократной записи при захвате
            -- мало: это гонка, а не пропуск.
            --
            -- ПОЧЕМУ С ВЫКЛЮЧАТЕЛЕМ. Ровно такой же сторож, поставленный
            -- сегодня на TargetOffset, превратился в 26 записей в секунду и
            -- владелец увидел дрожь камеры. Разница между «редкой правкой
            -- после чужого сброса» и «покадровой дракой» - это ЧИСЛО в
            -- единицу времени, и его надо не обещать, а мерить. Здесь оно
            -- меряется, и при превышении сторож ГАСИТ САМ СЕБЯ и говорит об
            -- этом вслух - потому что дрожащая камера хуже, чем сброшенный
            -- наклон.
            -- Новый угол - новый бюджет. Иначе выключатель, сработавший
            -- однажды, молча запрещал бы наклон до конца сессии, и владелец
            -- крутил бы клавишу в мёртвую ручку - ровно та беда, которую этот
            -- заход и лечит.
            if pitch_watch_for ~= cfg.camera_pitch then
                pitch_watch_for = cfg.camera_pitch
                pitch_restores, pitch_first_at, pitch_fight_off = 0, nil, false
            end
            if cfg.camera_pitch ~= 0 and not pitch_fight_off then
                local cam
                pcall(function() cam = owner.CameraThirdPerson end)
                if cam and cam:IsValid() then
                    local cr
                    pcall(function() cr = cam.RelativeRotation end)
                    local p = cr and cr.Pitch
                    if p and math.abs(p - cfg.camera_pitch) > 0.5 then
                        local was = p
                        pcall(apply_camera_pitch)
                        pitch_restores = pitch_restores + 1
                        if not pitch_first_at then pitch_first_at = os.clock() end
                        if pitch_restores <= 6 or pitch_restores % 50 == 0 then
                            log("наклон: игра поставила %.1f - вернул %.1f (раз %d)",
                                was, cfg.camera_pitch, pitch_restores)
                        end
                        -- Порог: тридцать возвратов за минуту. Редкий сброс
                        -- (смерть, смена режима) даёт единицы; покадровая
                        -- драка при опросе в 30 мс дала бы больше тысячи.
                        -- Между этими величинами тридцать - с большим запасом
                        -- в обе стороны.
                        local dt = os.clock() - pitch_first_at
                        if pitch_restores >= 30 and dt < 60 then
                            pitch_fight_off = true
                            say("НАКЛОН: игра возвращает своё %d раз за %.0f с - "
                                .. "ПРЕКРАЩАЮ бороться, иначе будет дрожь камеры. "
                                .. "Наклон останется игровым до перезахода.",
                                pitch_restores, dt)
                        end
                    end
                end
            end

            -- ЗАЩИТА ЦЕЛИ ЗУМА. Живую длину штанги не трогаем вовсе - владеем
            -- её целью, ровно как со смещением.
            --
            -- ⚠️ КАК ОТЛИЧИТЬ КОЛЕСО ОТ ЧУЖОГО СБРОСА. Два прежних правила
            -- оказались негодными и оба записаны, чтобы не вернуться к ним:
            --   1) "цель попала ровно в запомненное игрой число" - дыра в том,
            --      что владелец может САМ накрутить это число, и мод утащит
            --      камеру назад; вдобавок игра сбрасывает не всегда на него;
            --   2) то же самое плюс порог по скачку - лишняя опора на
            --      запомненное значение, от которой одни ложные срабатывания.
            -- Осталось то, что верно само по себе: КОЛЕСО ДВИГАЕТ ЦЕЛЬ НА ОДИН
            -- ШАГ (CameraZoomAmount = 20), А ИГРА - НА СОТНИ (в журнале видно
            -- "сбросила на 230, вернул 890"). Порог в три шага разделяет их с
            -- большим запасом и не зависит ни от каких запомненных чисел.
            if desired_zoom then
                local nz
                if pcall(function() nz = owner.NewTargetArmLength end) and nz then
                    -- ШАГ БЕРЁМ У ИГРЫ, А НЕ ИЗ ГОЛОВЫ.
                    -- Оплачено замером 09.09.2026: здесь стояло 20.0, порог
                    -- выходил 20*3 = 60, а игра двигает цель на CameraZoomAmount
                    -- = 69 ЗА ОДИН ЩЕЛЧОК. То есть КАЖДЫЙ щелчок колеса владельца
                    -- превышал порог и объявлялся "игра увела" - мод возвращал
                    -- свои 230 каждые 16 мс и дрался с владельцем. Владелец
                    -- описал это как "дёргается на большом и близком зуме, по
                    -- середине нет": по середине камера и так около 230, спорить
                    -- не о чем. Прогон харнесса: 29 перетягиваний за сессию, все
                    -- на "500.0" - то есть на том, куда сам же зум и отвёл.
                    -- Число 20 было догадкой; 69 игра печатает сама.
                    local step = 20.0
                    if cfg.zoom_step and cfg.zoom_step > 0 then
                        step = cfg.zoom_step
                    else
                        local za
                        if pcall(function() za = owner.CameraZoomAmount end)
                           and za and za > 0 then
                            step = za
                        end
                    end
                    local delta = math.abs(nz - desired_zoom)
                    -- Сброс узнаём ПО ЧИСЛУ, а не по величине сдвига: игра
                    -- всегда ставит одно и то же, колесо двигает от текущего
                    -- куда угодно. Прежний порог в три шага оставлен запасным -
                    -- им лечился рывок на спринте, где число другое.
                    local is_reset = game_reset_value ~= nil
                                     and math.abs(nz - game_reset_value) < 0.5
                                     and math.abs(desired_zoom - game_reset_value) > 0.5
                    -- СДАЁМСЯ, ЕСЛИ НЕ ПОБЕЖДАЕМ.
                    -- Замер харнессом 09.09.2026: мод вернул своё значение
                    -- ПЯТЬДЕСЯТ раз подряд, и все пятьдесят цель оставалась
                    -- чужой (500.0). Он не хозяин этому числу - а каждая
                    -- попытка дёргает штангу, и это ровно та дрожь, на которую
                    -- жаловался владелец ("дёргается на большом и близком зуме").
                    -- Проигранный бой надо прекращать, а не подбирать к нему
                    -- порог: если одно и то же чужое число возвращается снова и
                    -- снова, значит его поставили осознанно - принимаем его.
                    -- Проверка не зависит ни от каких угаданных величин.
                    -- Считаем ТОЛЬКО пока спор реально идёт (delta > 0.5).
                    -- Первая редакция считала каждый проход подряд, и порог
                    -- набегал в обычной работе - мод переставал спорить ВООБЩЕ,
                    -- в том числе там, где обязан: игра сбрасывает камеру после
                    -- смерти и на спринте. Дрожь ушла, но вместе с функцией;
                    -- замер этого не показал бы, потому что харнесс не умирает
                    -- и не спринтует. Поймано чтением журнала: строка "сдаюсь"
                    -- не напечаталась ни разу, а перетягиваний стало ноль -
                    -- две несовместимые вещи, значит объяснение было неверным.
                    if delta > 0.5 then
                        if lost_zoom_value ~= nil
                           and math.abs(nz - lost_zoom_value) < 0.5 then
                            lost_zoom_streak = lost_zoom_streak + 1
                        else
                            lost_zoom_value = nz
                            lost_zoom_streak = 1
                        end
                    else
                        lost_zoom_value = nil
                        lost_zoom_streak = 0
                    end
                    if lost_zoom_streak > LOST_ZOOM_GIVE_UP then
                        -- ПРИНИМАЕМ, НО В ГРАНИЦАХ.
                        -- Первая редакция принимала чужое значение КАК ЕСТЬ, и
                        -- вместе с дрожью исчез предел отдаления: владелец
                        -- 09.09.2026 - "нет лимита 3000, отдаляется до
                        -- бесконечности". Границы держит мод, и сдача в споре
                        -- за ЧИСЛО не означает отказа от СВОИХ ПРЕДЕЛОВ.
                        local lo = (type(cfg.zoom_min) == "number") and cfg.zoom_min or 60.0
                        local hi = (type(cfg.zoom_max) == "number") and cfg.zoom_max or 1000.0
                        local accepted = math.max(lo, math.min(hi, nz))
                        if desired_zoom ~= accepted then
                            log("зум: сдаюсь - %.1f вернулось %d раз подряд, принимаю %.1f (предел %.0f..%.0f)",
                                nz, lost_zoom_streak, accepted, lo, hi)
                        end
                        desired_zoom = accepted
                    end

                    if is_reset or delta > step * 3.0 then
                        local ok = pcall(function()
                            owner.NewTargetArmLength = desired_zoom
                        end)
                        if ok then
                            zoom_restores = zoom_restores + 1
                            if zoom_restores <= 6 or zoom_restores % 25 == 0 then
                                log("зум: игра увела цель на %.1f - вернул %.1f (раз %d)",
                                    nz, desired_zoom, zoom_restores)
                                -- ОТКУДА БЕРЁТСЯ ЧУЖОЕ ЧИСЛО. Замер показал, что
                                -- на спринте игра швыряет цель на 430, и с
                                -- мгновенным зумом камера успевает туда доехать
                                -- и вернуться - владелец видит это как
                                -- "неприятное отдаление". Чтобы вылечить
                                -- источник, надо знать, где это число лежит.
                                -- Читаем ТОЛЬКО известные по разведке имена -
                                -- перебора вслепую здесь нет и быть не должно.
                                for _, f in ipairs({
                                    "ThirdPersonCameraDefaultTargetArmLength",
                                    "ThirdPersonCameraMaxArmLength",
                                    "ThirdPersonCameraMinArmLength",
                                    "VanityCameraDefaultTargetArmLength",
                                    "VanityCameraMaxArmLength",
                                    "VanityCameraMinArmLength",
                                    "OriginalArmLength",
                                    "CameraZoomAmount",
                                }) do
                                    local v
                                    if pcall(function() v = owner[f] end) and v then
                                        log("    %s = %s", f, tostring(v))
                                    end
                                end
                            end
                        end
                    elseif delta > 0.5 then
                        desired_zoom = nz      -- это колесо владельца
                    end

                    -- ⚠️ ПОТОЛОК ПРОВЕРЯЕТСЯ ВСЕГДА, А НЕ ВНУТРИ ОДНОЙ ИЗ ВЕТОК.
                    -- Оплачено дважды за один вечер 09.09.2026.
                    -- Сперва зажима не было вовсе на пути "колесо владельца":
                    -- границы стояли только в ветке сдачи, и владелец сообщил
                    -- "не 30 метров у меня получается, а метров 100 или 200" -
                    -- то есть 10000..20000 при пределе 3000.
                    -- Потом зажим был поставлен В ЭТУ ветку - и снова мимо:
                    -- замер 23:15 (200 щелчков) дал цель 4260 при пределе 3000,
                    -- а зажим сработал ОДИН раз. Причина: быстрая прокрутка
                    -- даёт delta больше трёх шагов, и проход уходит в ПЕРВУЮ
                    -- ветку - ту, где мод считает движение чужой подменой.
                    -- Вывод, который стоил владельцу вечера: предел не бывает
                    -- частью ветки. Он проверяется на каждом проходе, кто бы ни
                    -- двигал число - игра, колесо или сам мод.
                    local lo = (type(cfg.zoom_min) == "number") and cfg.zoom_min or 60.0
                    local hi = (type(cfg.zoom_max) == "number") and cfg.zoom_max or 1000.0
                    if desired_zoom then
                        desired_zoom = math.max(lo, math.min(hi, desired_zoom))
                        update_interact_reach(owner, desired_zoom)
                    end
                    -- ⚠️ ЗАПИСЬ ПОТОЛКА В ИГРУ ОТСЮДА УБРАНА, И ЭТО ВАЖНЕЕ, ЧЕМ
                    -- выглядит. Сторож работает раз в 30 мс, а накопитель зума
                    -- игра ведёт быстрее: замер 09.09.2026 23:20 - наш зажим
                    -- ставил 3000, цель за то же время уходила на 6220, и камеру
                    -- рвало между двумя числами. Владелец: «на метров 30 отдаляю
                    -- - и начинаются рывки, словно она разрывается между далёкой
                    -- точкой и 30 метрами». ОПАЗДЫВАЮЩИЙ ПРЕДЕЛ ХУЖЕ, ЧЕМ ЕГО
                    -- ОТСУТСТВИЕ: он не ограничивает, а дёргает.
                    -- Слово владельца о том, как правильно: «логика должна быть,
                    -- а не ловить что-то по кадрам». Потолок обязан стоять ТАМ,
                    -- ГДЕ ЧИСЛО РОЖДАЕТСЯ - в функции зума блюпринта персонажа,
                    -- одним перехватом. Имя этой функции снимается разведкой
                    -- (ConanModPackStatus, probe_world_classes) - до тех пор
                    -- предела нет вовсе, и это честнее, чем предел, который
                    -- дёргает камеру.
                    -- ⚠️ ЗАЖИМ НАКОПИТЕЛЯ - И ТОЛЬКО ЕГО. ШТАНГУ НЕ ТРОГАЕМ.
                    -- Семья «перехватов» закрыта измерением: 09.09.2026 23:57
                    -- пять хуков (CameraZoomOut, CameraZoomIn, оба события ввода
                    -- колеса, AdjustCameraToSpringArm) встали и НЕ СРАБОТАЛИ ни
                    -- разу за 30 секунд - UE4SS этой сборки функции блюпринта не
                    -- перехватывает. Перебирать дальше членов той же семьи
                    -- дороже, чем выйти из неё (EXP-0061).
                    --
                    -- ПОЧЕМУ ЭТО НЕ ПОВТОР ТОГО, ЧТО РВАЛО КАМЕРУ. Рвало от
                    -- записи в ШТАНГУ: мод ставил ей 3000, а игра тянула её к
                    -- своей цели 6220, и камера металась между двумя числами.
                    -- Здесь штанга не трогается вовсе - правится только ЦЕЛЬ, к
                    -- которой игра тянет. Тянуть выше предела становится некуда,
                    -- и метаться не между чем.
                    --
                    -- И ГЛАВНОЕ - ЧИТАЕМ ОБРАТНО. За вечер дважды выяснялось,
                    -- что запись проходит без ошибки и ни на что не влияет.
                    -- Пока число не прочитано ПОСЛЕ записи, «зажал» - это вера.
                    -- ⚠️ СВОЙ ЗАЖИМ ВЫКЛЮЧЕН ПО УМОЛЧАНИЮ, И ЭТО РЕЗУЛЬТАТ
                    -- ИЗМЕРЕНИЯ, А НЕ ОСТОРОЖНОСТЬ. Замер 10.09.2026 00:10:
                    --     просили 1060 - записали 1000 - в поле теперь 1000
                    --     просили 4060 - записали 1000 - в поле теперь 1000
                    --     просили 5660 - записали 1000 - в поле теперь 1000
                    -- Запись ПРОХОДИТ (обратное чтение даёт ровно 1000) и тут же
                    -- затирается: игра считает расстояние где-то у себя, а
                    -- NewTargetArmLength лишь зеркалит её счёт каждый кадр.
                    -- Догнать зеркало нельзя - можно только мешать.
                    -- И мешали: пока зажим лежал сломанным (счётчик обращался к
                    -- имени, объявленному ниже, и pcall глотал ошибку), игра
                    -- держала предел САМА - владелец сказал "дёргается на 1000",
                    -- то есть камера ВСТАВАЛА на 1000. Стоило зажиму заработать,
                    -- как цель поехала до 5660. Наш зажим ломает игре её же
                    -- ограничение.
                    -- Предел держится теперь одним - записью cfg.zoom_max в
                    -- ThirdPersonCameraMaxArmLength (это делает apply_zoom_range).
                    -- Флаг оставлен, чтобы вернуть зажим одной строкой, если
                    -- когда-нибудь найдётся настоящий счётчик игры.
                    if cfg.zoom_cap_own and nz > hi + 0.5 then
                        pcall(function() owner.NewTargetArmLength = hi end)
                        local back
                        pcall(function() back = owner.NewTargetArmLength end)
                        zoom_cap_hits = zoom_cap_hits + 1
                        if zoom_cap_hits <= 6 or zoom_cap_hits % 100 == 0 then
                            log("предел: просили %.1f - записали %.1f - в поле теперь %s (раз %d)",
                                nz, hi, tostring(back), zoom_cap_hits)
                        end
                    end

                    -- ⚠️ ПРЯМАЯ ЗАПИСЬ ДЛИНЫ ОТМЕНЯЕТ ЛЮБУЮ ИНЕРЦИЮ.
                    -- Она появилась, когда притяжение было заглушено до 0.0001:
                    -- само оно камеру никуда не привело бы, и длину приходилось
                    -- ставить самим. Но запись мгновенная, и пока она есть, зум
                    -- щёлкает, сколько ни крути zoom_interp_speed - владелец
                    -- сказал прямо: «нет инерции, не то крутишь». Он прав.
                    -- Теперь это ВЫБОР: own_arm_length = true - мгновенно и
                    -- жёстко (как было), false - длину ведёт притяжение игры,
                    -- то есть плавно.
                    if cfg.own_arm_length then
                        local cur
                        if pcall(function() cur = arm.TargetArmLength end) and cur then
                            if math.abs(cur - desired_zoom) > 0.5 then
                                pcall(function() arm.TargetArmLength = desired_zoom end)
                            end
                        end
                    end
                end
            end

            -- ЗЕРКАЛО ДИСТАНЦИИ. Держим "дистанцию возврата в третье лицо"
            -- равной той, на которой камера сейчас. Тогда возврат режима
            -- (прыжок, спринт) возвращает камеру на прежнее место, а не на
            -- значение из настроек игры. Исключение - вид от первого лица:
            -- там дистанция возврата ставится в ближнюю границу, чтобы выход
            -- из FPV отдавал камеру в самое близкое третье лицо.
            local len
            if pcall(function() len = arm.TargetArmLength end) and len then
                -- ⚠️ ЗЕРКАЛИМ ЖЕЛАЕМУЮ ДИСТАНЦИЮ, А НЕ ТЕКУЩУЮ ДЛИНУ.
                -- Улика 09.09.2026, 02:25: игра в прыжке тянет цель к 280 - то
                -- есть ровно к тому числу, которое лежит в "дистанции возврата".
                -- А клал его туда сам мод, зеркаля ТЕКУЩУЮ длину, включая
                -- промежуточную, пока камера едет. Выходило, что мод своими
                -- руками подкладывал игре число, которым она потом дёргала
                -- камеру, - и паразитный зум был отчасти нашим собственным.
                -- Кладём желаемое: тогда сброс в прыжке ставит нашу же
                -- дистанцию, и двигаться некуда.
                local want
                if cfg.zoom_min and cfg.zoom_min >= 0 and len < cfg.zoom_min - 0.01 then
                    want = cfg.zoom_min            -- мы в FPV
                else
                    want = desired_zoom or len     -- обычное третье лицо
                end
                if not mirrored_zoom or math.abs(mirrored_zoom - want) > 0.5 then
                    local ok = pcall(function()
                        owner.ThirdPersonCameraDefaultTargetArmLength = want
                    end)
                    if ok then mirrored_zoom = want end
                end
            end

            -- ⚠️ СТОРОЖ СЧИТАЕТ ВРЕМЯ, А НЕ ПРОВЕРКИ. Первая версия считала три
            -- промаха подряд - и после спринта честно "ловила" законный переход,
            -- объявляла лечение неудачным и возвращала драку. Владелец увидел
            -- это как "после спринта появилась дрожь": сторож своими руками
            -- включал обратно ту самую болезнь. С интервалом 50 мс три проверки
            -- - это 150 миллисекунд, то есть срабатывало бы всегда.
            if os.clock() >= target_grace_until then
                local live
                if pcall(function() live = arm.SocketOffset end) and live then
                    local near = false
                    pcall(function()
                        near = math.abs(live.X - cfg.offset_x) < 12.0
                           and math.abs(live.Y - cfg.offset_y) < 12.0
                           and math.abs(live.Z - cfg.offset_z) < 12.0
                    end)
                    if near then
                        target_miss_since = 0
                    else
                        if target_miss_since == 0 then
                            target_miss_since = os.clock()
                        elseif os.clock() - target_miss_since >= 5.0 then
                            target_owned = false
                            log("ЛЕЧЕНИЕ НЕПОЛНО: цель наша пять секунд подряд, а камера "
                                .. "в X=%.1f Y=%.1f Z=%.1f. Возвращаюсь на удержание.",
                                live.X, live.Y, live.Z)
                        end
                    end
                end
            end
        end
    end
end

-- ⚠️ ШТАТНЫЙ ЦИКЛ ВМЕСТО САМОДЕЛЬНОЙ ЦЕПОЧКИ ИЗ ДВУХ ОЧЕРЕДЕЙ.
-- Было: ExecuteWithDelay (рабочий поток) -> ExecuteInGameThread (игровой), и так
-- по кругу. Документация UE4SS прямо советует для таймеров, которым и так место
-- на игровом потоке, брать API отложенных действий и не делать этот двойной
-- прыжок. Цена самоделки известна: 08.09.2026 два таких цикла разом (холостое
-- удержание 60/с и сторож 20/с) уронили игру - открытый баг #1180, падение в
-- process_simple_actions при накладывающихся ExecuteInGameThread.
-- ⛔️ НЕ ПОДХВАТЫВАТЬ ПРАВКИ ЭТОГО МОДА ЧЕРЕЗ Ctrl+R. Только перезапуском игры.
-- Цикл ниже вечный, и отменить его нечем: у LoopInGameThreadWithDelay нет API
-- остановки. Горячая перезагрузка не убирает старый цикл, а ДОБАВЛЯЕТ новый.
-- Ночь 09.09.2026: мод стартовал в одной сессии 38 раз, в игровом потоке
-- крутилось 38 сторожей разом - больше тысячи вызовов в секунду, - и игра
-- оборвалась с EXCEPTION_ACCESS_VIOLATION (стек из одних кадров UE4SS).
-- Коварство в том, что падение приходит НАКОПЛЕНИЕМ, и подозрение достаётся
-- последней правке, которая ни при чём. Разбор - EXP-0062.
local function start_target_watch()
    if type(LoopInGameThreadWithDelay) == "function" then
        LoopInGameThreadWithDelay(cfg.target_recheck_ms, function() pcall(keep_target_body) end)
        log("сторож цели: штатный цикл на игровом потоке, %d мс", cfg.target_recheck_ms)
    else
        log("штатного цикла в этой сборке UE4SS нет - иду цепочкой, %d мс",
            cfg.target_recheck_ms)
        local function chain()
            ExecuteInGameThread(function() pcall(keep_target_body) end)
            ExecuteInGameThreadWithDelay(cfg.target_recheck_ms, chain)
        end
        chain()
    end
end

-- ====== ПОДМЕНА ЗНАЧЕНИЯ В ИСТОЧНИКЕ (то, о чём просил владелец) ======
--
-- ЗАМЫСЕЛ ВЛАДЕЛЬЦА, дословно: "чтобы он тянул к нашей точке - то есть, не тянул
-- вовсе". Игра восстанавливает TPCameraSocketOffsetTarget из своей таблицы
-- настроек по режимам камеры. Если в таблице будет НАШЕ значение, то каждое
-- восстановление игры само поставит нашу точку - и тянуть станет некуда.
--
-- ⚠️ ТОЧЕЧНО. Трогается одно известное свойство CustomCamModeSettings, каждый
-- шаг в pcall: перебор ВСЕХ свойств персонажа 08.09.2026 уронил игру.
-- Имена полей внутри элемента неизвестны, поэтому пробуем список и печатаем,
-- какое подошло, - следующая правка будет по факту, а не по догадке.
local MODE_FIELDS = { "SocketOffset", "CameraSocketOffset", "SpringArmSocketOffset",
                      "Offset", "TPCameraSocketOffsetTarget" }

-- ⚠️ ПИШЕМ НЕ ВО ВСЕ РЕЖИМЫ, А ТОЛЬКО В ТРЕТЬЕЛИЧНЫЙ.
-- Опознаём его по данным, а не по номеру: у него в таблице лежит ровно то
-- значение, которое стояло в цели до нашего вмешательства. У прицеливания
-- своё - и оно должно остаться стоковым, камера обязана уходить вбок.
local function looks_like_stock(v)
    if not stock_target then return false end
    local same = false
    pcall(function()
        same = math.abs(v.X - stock_target.X) < 0.5
           and math.abs(v.Y - stock_target.Y) < 0.5
           and math.abs(v.Z - stock_target.Z) < 0.5
    end)
    return same
end

local function write_into_element(el, where)
    local hits = 0
    for _, f in ipairs(MODE_FIELDS) do
        local cur
        if pcall(function() cur = el[f] end) and cur ~= nil then
            local before = "?"
            pcall(function() before = ("X=%.1f Y=%.1f Z=%.1f"):format(cur.X, cur.Y, cur.Z) end)
            if not looks_like_stock(cur) then
                log("  %s.%s: %s - НЕ третьеличный режим, не трогаю", where, f, before)
            else
                local ok = pcall(function()
                    el[f] = { X = cfg.offset_x, Y = cfg.offset_y, Z = cfg.offset_z }
                end)
                log("  %s.%s: было %s -> %s", where, f, before,
                    ok and "записано наше" or "ЗАПИСЬ НЕ УДАЛАСЬ")
                if ok then hits = hits + 1 end
            end
        end
    end
    return hits
end

local function write_mode_table(owner)
    local tbl
    if not pcall(function() tbl = owner.CustomCamModeSettings end) or tbl == nil then
        log("ИСТОЧНИК: CustomCamModeSettings не прочиталось")
        return 0
    end
    local hits = 0

    local n
    if pcall(function() n = tbl:GetArrayNum() end) and type(n) == "number" and n > 0 then
        log("ИСТОЧНИК: массив режимов, элементов %d", n)
        for i = 1, math.min(n, 40) do
            local el
            if pcall(function() el = tbl[i] end) and el ~= nil then
                hits = hits + write_into_element(el, ("режим[%d]"):format(i))
            end
        end
        return hits
    end

    local iterated = false
    pcall(function()
        tbl:ForEach(function(key, value)
            iterated = true
            local el = value
            pcall(function() el = value:get() end)
            if el ~= nil then
                hits = hits + write_into_element(el, ("режим<%s>"):format(tostring(key)))
            end
        end)
    end)
    if iterated then return hits end

    log("ИСТОЧНИК: это не массив и не карта - пробую поля напрямую")
    return hits + write_into_element(tbl, "источник")
end

-- Расширение диапазона колёсика. Три числа у персонажа, пишутся там же, где
-- компонент становится выбранным - по уроку этого же вечера: настройка,
-- применённая на одной из веток выбора, молча не работает на другой.
apply_zoom_range = function(owner)
    if not (owner and owner:IsValid()) then return end
    local pairs_to_write = {
        { "ThirdPersonCameraMinArmLength", cfg.zoom_min },
        { "ThirdPersonCameraMaxArmLength", cfg.zoom_max },
        { "CameraZoomAmount",              cfg.zoom_step },
        { "TP_SpringArmInterpSpeed",       cfg.zoom_interp_speed },
        -- ⚠️ ThirdPersonCameraDefaultTargetArmLength здесь НЕ пишется.
        -- Жёсткая ближняя граница в этом поле дала баг: игра возвращает режим
        -- камеры после ПРЫЖКА и спринта - и сажала камеру на 60 вместо той
        -- дистанции, которую владелец накрутил колесом. Теперь это поле ведётся
        -- живьём в keep_target_body: оно всё время равно текущей дистанции
        -- игрока, поэтому возврат режима возвращает камеру туда же, где она и
        -- была, а сброс становится безвредным.
    }
    for _, pv in ipairs(pairs_to_write) do
        local field, want = pv[1], pv[2]
        if want and want >= 0 then
            local before
            pcall(function() before = owner[field] end)
            -- Поле читается не числом (23:12–23:13 «было TrivialObject») — это не живой герой: не пишем (падение 23:13:25).
            if type(before) ~= "number" then
                log("зум %s: поле читается как %s — не живой герой, запись пропущена", field, tostring(before))
                return
            end
            local ok = pcall(function() owner[field] = want end)
            log("зум %s: было %s -> %s", field, tostring(before),
                ok and ("%.0f"):format(want) or "ЗАПИСЬ НЕ УДАЛАСЬ")
        end
    end
end

local function adopt_arm(c, name)
    -- ⚠️ ДВА ЧИСЛА БЕРЁМ СРАЗУ, ИНАЧЕ СТОРОЖ НЕ РАБОТАЕТ ВОВСЕ.
    --   * desired_zoom появлялся ТОЛЬКО от колеса, а весь сторож зума живёт
    --     внутри `if desired_zoom`. Владелец колесо не крутит - значит сторож у
    --     него не работал ни разу, и паразитный зум в прыжке некому было чинить.
    --   * число сброса читаем ЗДЕСЬ, пока зеркало дистанции его не переписало:
    --     сразу после захвата в этом поле лежит стоковое значение игры. Это
    --     надёжнее всех признаков, которые пробовались 09.09 и провалились
    --     (порог по величине, кратность шага колеса, один щелчок за опрос) -
    --     разбор в KUMM/bugs/04.
    do
        local l
        if desired_zoom == nil
           and pcall(function() l = c.TargetArmLength end) and l and l > 0 then
            desired_zoom = l
            log("желаемая дистанция взята при захвате: %.1f", l)
        end
        if game_reset_value == nil then
            local a, v
            pcall(function() a = c:GetOwner() end)
            if a then pcall(function() v = a.ThirdPersonCameraDefaultTargetArmLength end) end
            -- ⚠️ ВРЕМЕННЫЙ ГЕРОЙ ПРИ ВХОДЕ В МИР (13.09.2026 22:04): игра на секунды создаёт
            -- второй BasePlayerChar_C, и у его штанги это поле — ОБЪЕКТ, а не число. Сравнение
            -- «v > 0» падало 36 раз подряд, камера ~35 с стояла не за спиной. Не число — герой
            -- не готов: штангу НЕ захватываем, поиск продолжится и найдёт настоящего.
            if v ~= nil and type(v) ~= "number" then
                not_ready_skips = not_ready_skips + 1
                if not_ready_skips == 1 then
                    log("штанга %s: владелец ещё не готов (поле сброса не число) - жду настоящего героя", tostring(name))
                end
                return
            end
            if v and v > 0 then
                game_reset_value = v
                log("число сброса игры взято при захвате: %.1f", v)
            end
        end
    end
    ever_adopted = true
    arm, arm_name = c, name

    -- ⚠️ ПЕРЕХВАТ ЗУМА ВЕШАЕМ ЗДЕСЬ, А НЕ ПО СОБЫТИЮ ПОЯВЛЕНИЯ ПЕРСОНАЖА.
    -- Измерено 09.09.2026 23:43: строк про перехват в журнале НОЛЬ - то есть
    -- установка не вызывалась ни разу. Причина: она висела на
    -- NotifyOnNewObject, а камера в том запуске нашлась запасным поиском, и
    -- событие не сработало. Место, где мы ТОЧНО стоим на ногах, ровно одно -
    -- вот это: штанга найдена, значит персонаж существует и его класс загружен.
    -- Общий урок: привязывать установку к событию, которое может не прийти, -
    -- то же самое, что не устанавливать её вовсе, только выглядит иначе.
    if try_install_zoom_hook then pcall(try_install_zoom_hook) end
    if cfg.disable_collision_test then
        local ok = pcall(function() arm.bDoCollisionTest = false end)
        log("щуп препятствий выключен: %s", ok and "да" or "не удалось")
    end
    if cfg.disable_camera_lag then
        local ok = pcall(function()
            arm.bEnableCameraLag = false
            arm.bEnableCameraRotationLag = false
        end)
        log("сглаживание камеры выключено: %s", ok and "да" or "не удалось")
    end
    apply()
    do
        local owner
        if pcall(function() owner = arm:GetOwner() end) then
            pcall(function() apply_zoom_range(owner) end)
            if owner and owner:IsValid() and not stock_zoom then
                pcall(function() stock_zoom = owner.NewTargetArmLength end)
                if stock_zoom then
                    desired_zoom = stock_zoom
                    log("зум: сохранённая игрой дистанция = %.1f (это значение сброса)",
                        stock_zoom)
                end
            end
        end
    end
    -- Разведка типов запускается В КОНЦЕ ФАЙЛА, а не здесь.
    -- ⚠️ ОПЛАЧЕНО ОШИБКОЙ: вызов стоял тут, а сама probe_types объявлена ниже
    -- по файлу (строка ~1008). Локальная функция, объявленная ПОЗЖЕ места
    -- вызова, попадает в замыкание как nil - и отложенное действие падало с
    -- LUA_ERRRUN на каждом заходе. В Lua порядок объявления локальных функций
    -- значит ровно то, что значит; писать вызов "выше" определения нельзя.
    if cfg.set_pull_target then
        remember_stock_target()
        target_owned = write_pull_target(false)
        if not target_owned then
            log("цель притяжения записать НЕ удалось - остаюсь на старом удержании")
        else
            -- Подмена в источнике: чтобы восстановление игры возвращало НАШЕ.
            local owner
            if cfg.try_source_table
               and pcall(function() owner = arm:GetOwner() end) and owner and owner:IsValid() then
                local hits = 0
                pcall(function() hits = write_mode_table(owner) end)
                if hits > 0 then
                    source_owned = true
                    -- Источник наш: частый опрос больше не нужен, он остаётся
                    -- молчаливым сторожем. Ноль перезаписей в журнале и будет
                    -- доказательством, что игра перестала тянуть.
                    cfg.target_recheck_ms = 1000
                    log("ИСТОЧНИК НАШ: полей переписано %d. Опрос переведён в редкий сторож.", hits)
                else
                    log("ИСТОЧНИК не поддался: знакомых полей не нашлось. "
                        .. "Держу цель проверкой раз в %d мс.", cfg.target_recheck_ms)
                end
            end
        end
    end
    -- ⚠️ РАЗВЕДКА ЗДЕСЬ БОЛЬШЕ НЕ ЗАПУСКАЕТСЯ, И ЭТО ВАЖНО.
    -- 08.09.2026 перебор свойств персонажа УРОНИЛ ИГРУ: EXCEPTION_ACCESS_VIOLATION
    -- по адресу 0x7378 (разыменование пустой ссылки при чтении объектного
    -- свойства), весь стек - UE4SS. Первый раз перебор прошёл целиком и дал то,
    -- ради чего затевался: имя цели TPCameraSocketOffsetTarget. Второй раз упал
    -- на PreVanity3PCameraStatus. Вывод: перебор чужих свойств - разовый
    -- разведочный инструмент, а не то, что живёт в рабочем моде. Функция
    -- оставлена и вызывается ТОЛЬКО с Numpad 7, руками и осознанно.
end

