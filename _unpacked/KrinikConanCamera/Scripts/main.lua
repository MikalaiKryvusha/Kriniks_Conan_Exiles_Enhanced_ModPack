local function dump_props(obj, label)
    if not (obj and obj:IsValid()) then log("  %s: нет", label); return end
    log("  %s: %s", label, obj:GetFullName())
    local cls = obj:GetClass()
    local shown = 0
    local ok = pcall(function()
        cls:ForEachProperty(function(prop)
            local n
            local okn = pcall(function() n = prop:GetFName():ToString() end)
            if not okn or not n then return end
            local low = n:lower()
            if low:find("cam") or low:find("offset") or low:find("socket")
               or low:find("arm") or low:find("target") or low:find("desired") then
                local okv, v = pcall(function() return obj[n] end)
                local text
                if not okv then
                    text = "<не прочиталось>"
                elseif type(v) == "userdata" then
                    local okx, x = pcall(function()
                        return ("X=%.2f Y=%.2f Z=%.2f"):format(v.X, v.Y, v.Z)
                    end)
                    text = okx and x or "<структура>"
                else
                    text = tostring(v)
                end
                shown = shown + 1
                log("      %s = %s", n, text)
            end
        end)
    end)
    if not ok then
        log("      (перебор свойств этой сборкой UE4SS не поддержан)")
    elseif shown == 0 then
        log("      (подходящих свойств не нашлось)")
    end

    local okf = pcall(function()
        cls:ForEachFunction(function(fn)
            local n
            local okn = pcall(function() n = fn:GetFName():ToString() end)
            if okn and n and n:lower():find("cam") then
                log("      функция: %s", n)
            end
        end)
    end)
    if not okf then log("      (перебор функций не поддержан)") end
end

