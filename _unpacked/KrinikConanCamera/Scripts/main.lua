-- ============ ОСМОТР ИСТОЧНИКА, ИЗ КОТОРОГО ИГРА ВОССТАНАВЛИВАЕТ ЦЕЛЬ ============
--
-- ЗАЧЕМ. Запись в TPCameraSocketOffsetTarget работает, но игра восстанавливает
-- свою при смене режима камеры, и мод возвращает нашу раз в 50 мс. Чтобы убрать
-- и это, надо подменить ЗНАЧЕНИЕ В ИСТОЧНИКЕ - таблице CustomCamModeSettings.
-- Тогда восстановление игры будет писать наше, и проверка станет не нужна.
--
-- ⚠️ ТОЧЕЧНО, А НЕ ПЕРЕБОРОМ. 08.09.2026 перебор всех свойств персонажа уронил
-- игру (EXCEPTION_ACCESS_VIOLATION при чтении объектного свойства). Поэтому
-- здесь трогается ОДНО известное свойство, каждый шаг в pcall, и вызывается это
-- только руками с Numpad 7 - чтобы никогда не сработать само посреди игры.
-- ============ РАЗВЕДКА ТИПОВ (безопасная: имена и типы, БЕЗ чтения значений) ============
--
-- ЗАЧЕМ ИМЕННО ТАК. Подменить таблицу стоков не вышло, потому что я угадывал
-- имена полей внутри CustomCamModeSettings. Узнать устройство мешал страх: 08.09
-- перебор свойств персонажа уронил игру. Но упало тогда на ЧТЕНИИ ЗНАЧЕНИЙ
-- (obj[name] по объектному свойству, EXCEPTION_ACCESS_VIOLATION 0x7378), а
-- перечисление ИМЁН И ТИПОВ значений не трогает вовсе. Полное имя свойства в
-- Unreal начинается с его класса - ArrayProperty / MapProperty / StructProperty
-- и так далее, - поэтому одного GetFullName() достаточно, чтобы понять, чем на
-- самом деле является таблица режимов и как в неё писать.
local function probe_types()
    log("---- ТИПЫ КАМЕРНЫХ СВОЙСТВ ПЕРСОНАЖА (без чтения значений) ----")
    if not (arm and arm:IsValid()) then log("  штанги нет"); return end
    local owner
    if not pcall(function() owner = arm:GetOwner() end) or not (owner and owner:IsValid()) then
        log("  персонажа нет"); return
    end
    local cls
    if not pcall(function() cls = owner:GetClass() end) or not cls then
        log("  класс не получен"); return
    end
    local shown = 0
    local ok = pcall(function()
        cls:ForEachProperty(function(prop)
            local full
            if not pcall(function() full = prop:GetFullName() end) or not full then return end
            local low = full:lower()
            if low:find("cam") or low:find("modesettings") or low:find("armlength") then
                shown = shown + 1
                if shown <= 60 then log("  %s", full) end
            end
        end)
    end)
    if not ok then log("  перечисление свойств не поддержано этой сборкой UE4SS")
    else log("  всего подходящих свойств: %d", shown) end
    log("---- КОНЕЦ ----")
end

local function probe_cam_mode_settings()
    log("---- ОСМОТР CustomCamModeSettings ----")
    if not (arm and arm:IsValid()) then log("  штанги нет"); return end
    local owner
    if not pcall(function() owner = arm:GetOwner() end) or not (owner and owner:IsValid()) then
        log("  персонажа нет"); return
