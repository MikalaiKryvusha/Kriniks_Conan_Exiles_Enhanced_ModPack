    if after == false then
        mute_hits = mute_hits + 1
        if mute_hits <= 6 or mute_hits % 25 == 0 then
            log("чужая камера заглушена: %s (раз %d)", cname, mute_hits)
        end
    else
        mute_fail = mute_fail + 1
        if mute_fail <= 3 then
            log("глушение %s НЕ ДЕРЖИТСЯ: запись %s, тик после неё %s",
                cname, ok and "прошла" or "отказала", tostring(after))
        end
    end
end

local function mute_foreign_camera()
    if not cfg.mute_foreign_camera then return end
    local now = os.clock()
    if now - last_mute_check < 1.0 then return end
    last_mute_check = now
    for _, cname in ipairs(FOREIGN_CAM_CLASSES) do
        local list
        if pcall(function() list = FindAllOf(cname) end) and list then
            for _, c in ipairs(list) do
                local alive = false
                pcall(function() alive = c:IsValid() end)
                if alive then mute_one(c, cname) end
            end
        end
    end
end

