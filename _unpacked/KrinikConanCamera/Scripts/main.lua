-- ПОКАДРОВОЕ УДЕРЖАНИЕ. Штатный механизм UE4SS: LoopInGameThreadAfterFrames
-- крутится на игровом потоке по разу на кадр. Он требует хука EngineTick,
-- поэтому обязателен вопрос EngineTickAvailable - так велит документация
-- (docs.ue4ss.com, Delayed Actions). Если сборка UE4SS его не знает, молча
-- падаем на прежний путь: хук, а не выйдет - таймер.
local function start_per_frame()
    rate_limit = false
    per_frame_running = true   -- камера первого лица выносится по углу взгляда в этом же цикле (fp_cam_tick)
    LoopInGameThreadAfterFrames(1, function()
        if fp_cam_on then
            local ok, e = pcall(fp_cam_tick)
            if not ok then fp_cam_on = false; log("камера от первого лица: ошибка в покадровой проверке — выключена до смены вида: %s", tostring(e)) end
        end
        if fp_recheck[1] then pcall(fp_recheck_tick) end   -- повторные проходы после смены оружия (убранный лук ложится за спину с задержкой)
        pcall(hold_camera)
    end)
    log("удержание ПОКАДРОВОЕ: по разу на кадр, ограничитель снят")
end

local per_frame_ok = (type(LoopInGameThreadAfterFrames) == "function")
                     and (EngineTickAvailable == true)

if cfg.reapply_enabled and cfg.prefer_per_frame and per_frame_ok then
    start_per_frame()
elseif cfg.reapply_enabled then
    if cfg.prefer_per_frame then
        log("покадрового цикла в этой сборке UE4SS нет (LoopInGameThreadAfterFrames=%s, "
            .. "EngineTickAvailable=%s) - иду прежним путём",
            type(LoopInGameThreadAfterFrames), tostring(EngineTickAvailable))
    end
    local installed = nil
    for _, path in ipairs(HOOK_CANDIDATES) do
        local ok = pcall(function() RegisterHook(path, hold_camera) end)
        if ok then
            installed = path
            break
        end
        log("хук не встал: %s", path)
    end

    if installed then
        log("хук %s встал — проверяю через 5 секунд, шевелится ли он", installed)
        -- ⚠️ «ВСТАЛ» И «РАБОТАЕТ» — РАЗНЫЕ УТВЕРЖДЕНИЯ, и это тоже оплачено:
        -- RegisterHook возвращает успех, даже если функция ни разу не будет
        -- вызвана. Поэтому считаем вызовы и не верим самому факту установки.
        ExecuteInGameThreadWithDelay(5000, function()
            if hold_calls > 0 then
                log("хук живой: %d вызовов за 5 секунд", hold_calls)
            else
                start_timer("хук встал, но не сработал ни разу")
            end
        end)
    else
        start_timer("ни один хук не встал")
    end
else
    log("удержание ВЫКЛЮЧЕНО в config.lua")
end

