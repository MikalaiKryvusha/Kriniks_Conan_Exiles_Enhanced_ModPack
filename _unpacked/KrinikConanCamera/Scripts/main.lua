--     «Разделать труп»). Поэтому сдвиг назад живёт в штанге (offset_x = 0 в config.lua, границы колёсика +125), а поиск камней от
--     отдаления больше не зависит: родные 25 + сдвиг назад (если его снова дадут) + запас владельца.
local function update_interact_reach(owner, arm_len)
    if type(arm_len) ~= "number" then return end
    if reach_arm_written and math.abs(arm_len - reach_arm_written) < REACH_STEP_CM then return end
    if not (owner and owner:IsValid()) then return end
    local pc
    pcall(function() pc = owner:GetController() end)
    if not (pc and pc:IsValid()) then return end
    local back = math.max(0.0, -(cfg.offset_x or 0.0))
    local extra = (type(cfg.interact_reach_extra_cm) == "number") and cfg.interact_reach_extra_cm or 0.0
    local pickup = VANILLA_PICKUP_CM + back + extra
    if pcall(function() pc.PickupInteractionDistance = pickup end) then
        reach_arm_written = arm_len
        log("дальность взятия: поиск камней %.0f см от героя (сдвиг назад %.0f, запас %.0f); луч взаимодействия ведёт игра по штанге %.0f",
            pickup, back, extra, arm_len)
    end
end

local function apply(with_distance)
    if not arm or not arm:IsValid() then return false end
    reach_arm_written = nil   -- сдвиг offset_x мог смениться — надбавку пересчитать при следующей записи зума
    -- Наклон ставим ДО записи в штангу и вне общего pcall ниже: он живёт на
    -- другом объекте, и его отказ не должен отменять смещение камеры.
    pcall(apply_camera_pitch)
    -- ⚠️ ПИШЕМ СТРУКТУРУ ЦЕЛИКОМ, А НЕ ПО ПОЛЯМ.
    -- Первая версия делала arm.SocketOffset.X = v — и это МОЛЧА НЕ РАБОТАЛО:
    -- UE4SS отдаёт структурное свойство КОПИЕЙ, правка полей копии в объект не
    -- попадает, ошибки при этом нет. Симптом у владельца был точный: числа в
    -- config.lua меняются с нумпада, а камера стоит на месте.
    local ok, err = pcall(function()
        arm.SocketOffset = { X = cfg.offset_x, Y = cfg.offset_y, Z = cfg.offset_z }
        -- Ось вращения. Пишется той же записью и по тому же правилу: структуру
        -- ЦЕЛИКОМ, потому что UE4SS отдаёт её копией.
        arm.TargetOffset = { X = cfg.target_offset_x,
                             Y = cfg.target_offset_y,
                             Z = cfg.target_offset_z }
        -- Дистанцию трогаем только когда её и просили менять, ИЛИ пока колесом
        -- ещё не пользовались (desired_zoom пуст - значит владеем мы).
        if cfg.arm_length >= 0 and (with_distance or desired_zoom == nil) then
            arm.TargetArmLength = cfg.arm_length
        end
    end)
    if not ok then
        log("запись в компонент не удалась: %s", tostring(err))
        return false
    end
    return true
end

