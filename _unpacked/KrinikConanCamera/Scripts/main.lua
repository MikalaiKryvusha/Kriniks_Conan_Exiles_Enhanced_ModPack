-- ⚠️ zoom_cap_hits здесь БОЛЬШЕ НЕ ОБЪЯВЛЯЕТСЯ: он живёт наверху файла, выше
-- всех мест использования. Второе объявление здесь было бы не безобидным
-- дублем, а ловушкой - оно перекрывало бы верхнее только для кода НИЖЕ себя, и
