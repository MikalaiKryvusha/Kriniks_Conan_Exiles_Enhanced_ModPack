-- Первые попытки частые - в мире камера находится за секунду-две; дальше
-- интервал вырастает впятеро, потому что частый опрос в меню всё равно бесполезен.
-- Главный вход остался прежним и событийным: NotifyOnNewObject на появление
-- персонажа. Этот поиск - только страховка.
local SEARCH_FAST_MS  = 1000
local SEARCH_SLOW_MS  = 5000
local SEARCH_FAST_TRIES = 10        -- сколько попыток идут часто
local SEARCH_MAX_TRIES  = 130       -- ~10 минут, дальше молчим и ждём Numpad 0
local search_tries = 0

-- Переходник: probe_types объявлена НИЖЕ по файлу, и взять её здесь напрямую
-- нельзя - в замыкание она попадёт как nil (класс, описанный в docs/06).
-- Значение присваивается в конце файла, до первого срабатывания таймера.
local pending_probe_types = nil

local function keep_searching()
    if arm and arm:IsValid() then return end          -- уже нашли
    search_tries = search_tries + 1
    if search_tries > SEARCH_MAX_TRIES then
        log("поиск прекращён после %d попыток. Нажми Numpad 0, когда будешь в мире.",
            SEARCH_MAX_TRIES)
        return
    end
    ExecuteInGameThread(function()
        local c, name = pick_arm()
        if c then
            log("ВЫБРАН компонент: %s  (попытка %d)", name, search_tries)
            adopt_arm(c, name)
            -- Разведка типов больше не живёт отдельной цепочкой: она делается
            -- один раз здесь, сразу после того, как штанга найдена.
            if pending_probe_types then ExecuteInGameThread(pending_probe_types) end
        end
    end)
    local next_ms = (search_tries < SEARCH_FAST_TRIES) and SEARCH_FAST_MS or SEARCH_SLOW_MS
    ExecuteInGameThreadWithDelay(next_ms, keep_searching)
end

ExecuteInGameThreadWithDelay(SEARCH_FAST_MS, keep_searching)

