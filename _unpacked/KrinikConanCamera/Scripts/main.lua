local function load_config()
    local f = io.open(CONFIG_PATH, "r")
    if not f then
        log("config.lua не найден, беру умолчания")
        return
    end
    f:close()
    local ok, loaded = pcall(dofile, CONFIG_PATH)
    if ok and type(loaded) == "table" then
        -- ⚠️ СТОРОЖ ПОДМЕНЫ. Оплачено вечером 09.09.2026 тремя часами владельца.
        -- Мод сам переписывает config.lua при подкрутке с нумпада и пишет туда
        -- ВСЕ ключи разом. Значит однажды сохранённое значение НАВСЕГДА
        -- побеждает новое значение в коде - и правка, сделанная в главном
        -- файле, до игры не доезжает. Так молча отменились три лекарства того
        -- же вечера (zoom_interp_speed, disable_collision_test,
        -- prefer_per_frame), и снаружи это выглядело как "починили - не
        -- помогло", а владелец три часа повторял "что-то мешает".
        -- Молчаливую подмену лечит не осторожность, а ПЕЧАТЬ: мод обязан сам
        -- называть каждый ключ, где файл перебил код. Смещения и дистанцию
        -- владелец крутит руками - для них расхождение НОРМА и в список не идёт.
        local owner_tuned = {
            offset_x = true, offset_y = true, offset_z = true, arm_length = true,
        }
        local overridden = {}
        for k, v in pairs(loaded) do
            if cfg[k] ~= nil and type(v) == type(cfg[k]) then
                if v ~= cfg[k] and not owner_tuned[k] then
                    overridden[#overridden + 1] =
                        ("%s: код %s -> файл %s"):format(k, tostring(cfg[k]), tostring(v))
                end
                cfg[k] = v
            end
        end
        log("config.lua прочитан")
        if #overridden > 0 then
            table.sort(overridden)
            -- Печатаем МИМО logging_enabled: если файл перебил и его самого,
            -- сообщение о подмене исчезло бы вместе с остальным журналом -
            -- то есть сторож молчал бы ровно в том случае, ради которого он есть.
            say("ВНИМАНИЕ: config.lua перебил %d настроек кода:", #overridden)
            for _, line in ipairs(overridden) do say("    %s", line) end
        end
    else
        log("config.lua не разобран, беру умолчания: %s", tostring(loaded))
    end
end

