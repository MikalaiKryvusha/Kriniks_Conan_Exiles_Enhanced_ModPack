-- "моя штанга ещё цела?" отвечает ДА, пересбор не запускается, и мод навсегда
-- держит мёртвую камеру, не трогая настоящую. Владелец видит это как
-- "после смерти камера за плечом" - и это регрессия: 08.09 работало.
-- Вывод общий: недостаточно спрашивать, ЖИВА ЛИ моя штанга. Надо спрашивать,
-- ТА ЛИ ОНА.
local DEAD_CAM_MARK = "DeathCameraActor"

local function pick_arm()
    local found = dump_candidates()
    if #found == 0 then return nil end

    -- Отбрасываем штанги камеры смерти ДО всякого выбора: пока владелец мёртв,
    -- чинить нечего, и лучше подождать настоящую камеру, чем взять чужую.
    local alive = {}
    for _, c in ipairs(found) do
        local n = nil
        pcall(function() n = c:GetFullName() end)
        if n and not n:find(DEAD_CAM_MARK, 1, true) then alive[#alive + 1] = c end
    end
    if #alive == 0 then
        log("есть только штанга камеры смерти - жду настоящую")
        return nil
    end
    found = alive

    if cfg.force_component_name ~= "" then
        for _, c in ipairs(found) do
            if c:IsValid() and c:GetFullName():find(cfg.force_component_name, 1, true) then
                return c, c:GetFullName()
            end
        end
        log("компонент по имени %q не найден, подбираю сам", cfg.force_component_name)
    end

    -- Предпочтения по убыванию правдоподобия. Имена — гипотезы из серверного
    -- дампа и из чужих модов, поэтому именно СПИСОК, а не одно имя.
    local prefer = { "ThirdPerson", "CameraThirdPerson", "CameraBoom", "SpringArm" }
    for _, want in ipairs(prefer) do
        for _, c in ipairs(found) do
            if c:IsValid() and c:GetFullName():find(want, 1, true) then
                return c, c:GetFullName()
            end
        end
    end

    for _, c in ipairs(found) do
        if c:IsValid() then return c, c:GetFullName() end
    end
    return nil
end

